export const OP_SCREEN = {};

/** Екран цієї операції — або порожньо, якщо такого екрана в застосунку немає. */
export const screenOfOp = (op) => {
  const want = OP_SCREEN[op] || '';
  return want && SCREENS[want] ? want : '';
};

