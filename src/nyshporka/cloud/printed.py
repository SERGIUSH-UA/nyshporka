"""🖨 Друк у хмарі: чим захід газети відрізняється від заходу рукописної справи.

Друковане видання (газету, журнал, довідник) читає не рукописний рушій, а
PaddleOCR-VL через vLLM. 🔴 Рушій друку живе ЛИШЕ на орендованій машині — у
пакеті оренди (`gpuhire`, `_embedded/print_vl_worker.py`): локального друку в
Нишпорці немає свідомо. Paddle з vLLM важать гігабайти й хочуть карту на
20+ ГБ, а більшості людей друк не потрібен.

Тут — лише те, що Нишпорка передає наглядачеві, щоб захід поїхав рушієм друку,
і куди лягає прочитане. Решта шляху (кадри, R2, оренда, забір) — той самий
`cloud go`. Номер іде під іменем і ключем видання (`print_edition.IssueRun`),
а кадри, залиті колись під іншою адресою, наглядач бере звідти (`--reuse-key`).
"""
from __future__ import annotations

from pathlib import Path

#: Рушій друку в плані наглядача (`-p engine=…`).
ENGINE = "paddle_vl"
#: Модель, під якою текст ляже в мету: забір звіряє її з `model` плану.
MODEL = "PaddleOCR-VL-1.6-0.9B"
#: Письмо заходу друку — окреме значення, а не «кирилиця»: рушій читає будь-яке.
SCRIPT = "print"
#: Друк читається лише конвеєром наглядача, а справа частинами туди не йде:
#: межа частини свідомо понад будь-який номер газети чи том.
PART_PAGES = 100_000


def out_root() -> Path:
    """Куди лягають номери: поза `reports/htr`.

    🔴 Номер газети — не справа архіву: ім'я теки «3 (770) 1936-01-06» резолвер
    розібрав би на числа й приписав би чужій справі №770. До пошуку номери
    потрапляють лише зібраними в роки видання (`VYD/<код>/<рік>`).
    """
    from nyshporka.core.workspace import workspace

    return workspace().derived / "print" / "issues"


def plan_params() -> list[str]:
    """Параметри наглядача, що роблять захід заходом друку: лише рушій.

    🔴 Ворота машини (Ampere, VRAM, диск, ціна тисячі сторінок, датацентри,
    темп) вшиті в наглядача за самим `engine` (`gpuhire`, `core/print_engine.py`).
    Доти їх ніс цей перелік, і перший живий захід падав саме на тих, яких
    тут не було: план, складений будь-ким, мусить отримати ті самі ворота.
    """
    return [f"engine={ENGINE}", f"script={SCRIPT}"]


def is_print(script: str) -> bool:
    return str(script or "") == SCRIPT
