"""🔤 Порівняння заголовків і ключів справ — чисті згортки злиття.

🔴 Пороги тут не з голови: кожен виміряний на живому фонді, і числа лишились у
коментарях навмисно. Це не історія, а причина, чому поріг саме такий, — без неї
наступний «оптимізує» його й дістане тисячі хибних розбіжностей у черзі ока.

⚠ `rapidfuzz` тут НЕ вживається, хоч і є в залежностях. Схожість заголовків
міряється власним коефіцієнтом Жаккара по токенах: він СТРОГІШИЙ за однойменну
функцію бібліотеки й відкалібрований разом із порогом 0.45. Підміна на
бібліотечну змінила б поріг мовчки.
"""
from __future__ import annotations

import re
from collections.abc import Mapping
from difflib import SequenceMatcher

#: Номер справи з алфавітки або суцільного поля: «2543», «1280а».
#: 🔴 Клас літери мусить нести українські «і ї є ґ» ЯВНО: діапазон «а-я» їх не
#: містить, тож справа «1280і» не читалась як літерна взагалі — рядок мовчки
#: випадав, і в черзі завантаження на його місці не було нічого. Описи ДАХмО
#: і ДАВіО набирали українською, тож клас має покривати обидва алфавіти.
_RE_SPR = re.compile(r"^(\d+)\s*([а-яіїєґa-z]?)$", re.IGNORECASE)

#: Розкриття архівних скорочень ПЕРЕД звіркою.
#: 🔴 Сюди не можна додавати стоп-слова. Розкриття лише ДОДАЄ спільних токенів,
#: тобто робить звірку м'якшою; викидання «метрична книга церкви» зробило б її
#: строгішою й роздуло чергу розбіжностей рівно там, де джерела згодні.
_ABBREV = ((r"\bсв\b", "святого"), (r"\bпов\b", "повіту"), (r"\bуезд\b", "повіту"),
           (r"\bуѣзд\b", "повіту"), (r"\bгуб\b", "губернії"), (r"\bц\b", "церкви"))

#: Класи, що реально ламають OCR цих описів: «щ»↔«ш», тверді/м'які знаки,
#: «ы»→«и», «э»→«е», і цифроподібні «о»→«0», «з»→«3».
_CONFUSE = (("щ", "ш"), ("ъ", ""), ("ь", ""), ("ы", "и"), ("э", "е"),
            ("о", "0"), ("з", "3"))

#: Чи називає рядок ПОСЕЛЕННЯ взагалі — без цього питати з нього село марно.
_RE_SETTLEMENT = re.compile(r"(?:^|\s)(?:сс?|м|м-к[оаиу]|с-щ[еаі]|сл)\.\s*[А-ЯІЇЄҐ]")
_RE_VILLAGE_OF = re.compile(
    r"(?:^|[\s·,])(?:сс?|м|м-к[оаиу]|с-щ[еаі]|сл)\.\s*([А-ЯІЇЄҐ][\w'’\-]+)")

#: Літерний індекс справи — кириличний у шифрі архіву, але джерела пишуть його
#: як заманеться.
#: 🔴 Заміряно на ф.230 спр.24а: в описі й на дзеркалі літера кирилична, а ім'я
#: файла на Вікісховищі — «230-1-24a» ЛАТИНСЬКОЮ, бо так набрав заливач. Реєстр
#: через це роздвоював справу: рядок «24а» із заголовком і роками, але без
#: скана, і рядок «24a» з одним сканом і порожнім заголовком. Обидва потрапляли
#: в чергу завантаження як окремі позиції.
_LETTER_TO_CYR = {"a": "а", "b": "б", "v": "в", "g": "г", "d": "д", "e": "е"}


def norm_title(s: str) -> str:
    """Заголовок до порівнюваного вигляду: регістр, скорочення, класи плутанини.

    ⚠ Порядок кроків значущий: скорочення розкриваються ПІСЛЯ зведення «і»→«и»,
    тож шаблони в `_ABBREV` писані вже в цьому алфавіті.
    """
    t = (s or "").lower().replace("ё", "е").replace("і", "и").replace("ї", "и")
    t = re.sub(r"[^\w\s]+", " ", t)
    for pat, rep in _ABBREV:
        t = re.sub(pat, rep, t)
    for a, b in _CONFUSE:
        t = t.replace(a, b)
    return " ".join(t.split())


def token_set_ratio(a: str, b: str) -> float:
    """Частка спільних слів (Жаккар). 0.0 — порівнювати нічим."""
    ta, tb = set(norm_title(a).split()), set(norm_title(b).split())
    if not ta or not tb:
        return 0.0
    return len(ta & tb) / len(ta | tb)


def village_of(title: str) -> str:
    """Перше поселення, назване в заголовку; порожньо — жодного."""
    m = _RE_VILLAGE_OF.search(title or "")
    return norm_title(m.group(1)) if m else ""


def names_settlement(text: str) -> bool:
    """Чи згадує рядок поселення взагалі."""
    return bool(_RE_SETTLEMENT.search(text or ""))


def village_matches(village: str, text: str, thr: float = 0.8) -> bool:
    """Чи названо в `text` те саме поселення, що в `village`.

    🔴 Точний підрядок не працює в ОБИДВА боки, і кожен бік дає свій клас
    хибних тривог. Каталог пише повну форму («Вербка-Волоська»), назва файлу —
    коротку («с. Вербка»), тож «каталог у тексті» не знаходиться. А зворотне
    «текст у каталозі» ловилось би на будь-якому спільному складі.

    🔴 До того ж назви пишуть різною орфографією: каталог — «Стара Гарячківка»,
    файл — «Горячківка» (о/а в корені). Тому порівнюємо ПОСЛІВНО й посимвольно.
    Короткі слова (≤4 літери) не рахуються: «Стара», «Нова», «Мала» є в десятках
    назв і дали б збіг усюди.
    """
    vt = [w for w in norm_title(village).split() if len(w) > 4]
    tt = [w for w in norm_title(text).split() if len(w) > 4]
    if not vt or not tt:
        return True          # порівнювати нічим — мовчимо, а не звинувачуємо
    return any(SequenceMatcher(None, a, b).ratio() >= thr for a in vt for b in tt)


def letter_cyr(letter: str) -> str:
    """Літерний індекс до одного письма (кирилиця шифру). Незнану — як є."""
    return _LETTER_TO_CYR.get(letter, letter)


def opys_sort(o: str) -> tuple[int, int, str]:
    """Ключ сортування опису, стійкий до НЕЧИСЛОВИХ номерів.

    ⚠ Описи бувають «Л2», «ОРП41», «РП1» (ДАВіО ф.904) — на `int()` це клало
    всю перезбірку реєстру, тобто одна дивна позиція гасила решту фонду.
    Числові йдуть першими за значенням, решта — в хвіст за абеткою.
    """
    s = str(o).strip()
    m = re.match(r"^(\d+)(.*)$", s)
    return (0, int(m.group(1)), m.group(2)) if m else (1, 0, s)


def key_of(row: Mapping[str, str]) -> tuple[str, str, str] | None:
    """Ключ справи `(опис, номер, літера)`; `None` — рядок не звівся до справи.

    ⚠ Опис НЕ нормалізується (провідні нулі, «Л2» — як є): він і в шифрі такий.
    """
    o = str(row.get("opys") or "").strip()
    if not o:
        return None
    n = str(row.get("spr_int") or "").strip()
    letter = str(row.get("spr_letter") or "").strip().lower()
    if not n:
        # Суцільне поле `spr` («1280а») — так пишуть алфавітка й індекс плівок.
        m = _RE_SPR.match(str(row.get("spr") or "").strip())
        if not m:
            return None
        n, letter = m.group(1), m.group(2).lower()
    if not n.isdigit():
        return None
    return (o, n, letter_cyr(letter))
