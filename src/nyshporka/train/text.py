"""🔤 Чисті правила над текстом мітки — без залежностей і без зображень.

Тут лежить те, що мусить діяти однаково в трьох місцях: при записі мітки
рукою, при імпорті злиття арбітрів і при збірці корпусу. Правило, продубльоване
в трьох модулях, розходиться тихо; тут воно одне.
"""
from __future__ import annotations

import re

#: Маркер розбіжності голосів у чернетці: ``‹26|20›`` — «рушії розійшлись».
#: У чернетці він потрібен людині; у МІТЦІ — отрута.
_CONFLICT_MARK = re.compile(r"‹([^|›]*)\|[^›]*›")


def strip_conflict_marks(s: str) -> str:
    """Зняти маркери розбіжності, лишивши перший варіант.

    🔴 Обов'язково на кожному вході, де текст іде В МАШИНУ, а не в очі: мітка
    рукою, злиття арбітрів, корпус. Маркер, що потрапив у мітку, додає `‹ › |`
    в алфавіт моделі, і вона вчиться їх ГЕНЕРУВАТИ — після чого символи
    з'являються в декоді справ і ламають нечіткий пошук прізвищ. Заміряно в
    дослідницькому конвеєрі: 16 рядків із 724 псевдо-міток протекли саме так.
    """
    return _CONFLICT_MARK.sub(lambda m: m.group(1), s)


def has_conflict_marks(s: str) -> bool:
    return any(ch in s for ch in "‹›|")


_BABBLE_TOKEN = re.compile(r"[^\W_]+", re.UNICODE)
_BABBLE_DIGIT = re.compile(r"\d")


def is_babble(line: str) -> bool:
    """Чи це белькіт рушія на смужці без тексту, а не текст.

    Портрет: коротка смужка без цифр, ≥3 токени, жоден не дотягує до слова
    (5 літер), і серед них є повтор — рушій ходить по колу («по тому объ
    обу объ»). Кожна складова потрібна: без повтору це законний уривок
    («Въ селѣ Ходъ»), без розсипу — двоколонковий рядок із законним повтором
    у сусідній графі, з цифрами — числова комірка формуляра.

    🔴 Рушій не вміє мовчати: на порожній смужці він видає щось завжди, і без
    цих воріт такі рядки ідуть у корпус як «текст».
    """
    if len(line) >= 25 or _BABBLE_DIGIT.search(line):
        return False
    t = _BABBLE_TOKEN.findall(line)
    if len(t) < 3 or max(len(x) for x in t) >= 5:
        return False
    n = [x.lower().replace("ъ", "").replace("ь", "").replace("ѣ", "е") for x in t]
    return len(set(n)) < len(n)


#: Дореформені літери → сучасні для «м'якого» порівняння: там, де різні
#: орфографічні конвенції не мають рахуватися за помилку читання.
HIST_MAP = str.maketrans({"ѣ": "е", "ѳ": "ф", "ѵ": "и", "і": "и", "ї": "и",
                          "ъ": "", "ё": "е"})


def norm_loose(s: str) -> str:
    """Нижній регістр, дореформені літери згорнуті, пробіли стиснуті."""
    return " ".join(s.lower().translate(HIST_MAP).split())


def norm_strict(s: str) -> str:
    """Лише пробіли стиснуті — літери як у джерелі."""
    return " ".join(s.split())


def unify_i(s: str) -> str:
    """Латинська `i` → кирилична `і` там, де корпус змішує їх безсистемно."""
    return s.replace("i", "і").replace("I", "І")
