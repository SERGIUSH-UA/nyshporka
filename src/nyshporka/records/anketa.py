"""🗂 Анкета й картотека: прізвище з поля бланка, а не з частоти слів.

Картотека (облікові картки, анкети, фільтраційні справи) — інший жанр, ніж
метрика. Прізвище стоїть на картці ОДИН раз, поруч із підписом поля «1.
Фамилия», а найчастіші слова тексту — це підписи полів, що повторюються на
кожній картці. Частотний витяг прізвищ (поріг «двічі в справі») тут дає саме
підписи: «Фамилия», «Отчество», «Национальность».

Тому тут — витяг ПОЛЯ: знайти на лицьовому боці підпис поля прізвища й узяти
значення поруч. Заміряно на справжній картотеці (сегмент 8997 сторінок, два
голоси, 15.10.2026): лицьових боків 4379, прізвище витягнуто з 3155 (72 %);
обидва голоси дали те саме прізвище лише у 20 % — читання таких карток
слабке, і жодна з цих цифр не робить витягнуте фактом.

🔴 Рушій систематично калічить ПЕРШУ літеру рукописного прізвища на картці
(справжнє «Абченко» → «Рабченко», «Оадчено», «Баьченко»: у пачці на «Аб…»
друга-третя літери «аб» у 18 з 25 витягів, перша — будь-яка). Тому для
покажчика `varianty` дає й форму без першої літери: людина, що шукає
«Абченко», мусить знайти картку, прочитану як «Рабченко». Межі абетки з
витягнутого тексту, навпаки, НЕ рахуються: з хибною першою літерою вони були б
вгадані, а не виміряні.

Сторінка без підпису поля «Имя» у перших рядках (зворот картки, метрика,
ревізія) не дає нічого — витяг не зачіпає інших жанрів.
"""
from __future__ import annotations

import re
from collections import Counter
from collections.abc import Iterable

from nyshporka.records.names import known_given

#: Скільки перших рядків сторінки дивитись: поле прізвища — у шапці бланка.
SHAPKA = 14

#: Мінімальна довжина прізвища. Коротше — обрізок рушія («АБи», «еи»).
MIN_DOVZHYNA = 4

#: Підпис поля «Имя» — ознака лицьового боку. Рушій пише його «2. ИМЯ»,
#: «2 ИимяМ», «Иня». «Имя отца/матери» — зворот німецького бланка, не лице.
_IMIA = re.compile(r"(?:имя|\bи[мн]я\b)(?!\s*(?:отца|матери))", re.I)

#: Поле «Имя» стоїть у шапці: нижче — це вже інший розділ бланка.
SHAPKA_IMIA = 8

#: Підпис поля прізвища з каліченнями рушія: «1. Фамилия», «Фам.», «.МИЛИА»,
#: «Рм.К», «1. ам.», «.РамИЛИ», «ФАм».
#: 🔴 Скорочення «Фам.» — лише з крапкою чи кінцем слова після «ам»: інакше
#: підписом ставало б саме прізвище на «Рам…» («Рамзин»).
_FAM = re.compile(
    r"(?:^\W{0,3}1\s*[.,]\s*)?(?:[фрт]?\s*\.?\s*а\s*м(?:\.|(?![а-яёіїєґa-z]))"
    r"|\bр\s*м\s*\.|\w*амил\w*|\w*мили[яиа]\w*)\W*", re.I)

#: Підписи інших полів бланка — рядок із ними не є значенням.
_PIDPYSY = re.compile(
    r"фам|амил|мили[яиа]|имя|отч|отеч|год\s*р|рожд|мест|адре|спец|проф|нац|парт|служ|"
    r"граж|карточ|состав|фильтр|ближай|родств|решен|выбыл|направ|плен|угнан|прожив|"
    r"\bарх\b|орган|подпис|правильн|сведени|данн|степень|указат|дактил|"
    # Німецький бланк: «Vorname», «Name der Mutter» кирилицею рушія.
    r"огнат|огпат|ограт|орнам|vorn|\bнате\b|\bмате\b|"
    # Слова, що в шапці бланка стоять частіше за прізвище (заміряно).
    r"военн|призыв|заполн|оккупац|рмию|лагер|ество|честв|сумск|умск|немецк|емецк|"
    r"матер|оживаю|ионного", re.I)

#: По батькові — не прізвище («Иванович», «Петровна»).
_PO_BATKOVI = re.compile(r"(?:вич|вна|ична|чна)$", re.I)

#: Номер поля на початку рядка («4. Год…», «12 Орган»).
_NOMER = re.compile(r"^\W{0,3}\d{1,2}\s*[.,:]")

_SLOVO = re.compile(r"[А-ЯЁІЇЄҐа-яёіїєґѣѳъ]+")

#: Літери й закінчення, яких після реформи 1918 року в російському тексті
#: немає (ѣ ѳ ѵ, кінцевий ъ, родовий «-аго/-яго»): їх поява в документі ХХ ст.
#: — ознака того, що модель вигадує.
_DOREFORMENI = re.compile(r"[ѣѳѵ]|ъ\b|[ая]го\b", re.I)
_KYRYLYTSIA = re.compile(r"[А-ЯЁІЇЄҐа-яёіїєґѣѳѵъ]{3,}")


def _zlyty(riadok: str) -> str:
    """Значення з рядка: перше слово ≥4 літер, або рознесені рушієм склади.

    «ам цо ва» → «амцова»: шматки по 1–3 літери склеюються, бо рушій рве
    рукописне слово на склади. Слово з довшим шматком серед коротких — уже не
    склади, і тоді береться найперше довге.
    """
    shm = _SLOVO.findall(riadok)
    if len(shm) >= 2 and all(len(s) <= 3 for s in shm):
        return "".join(shm)
    dovgi = [s for s in shm if len(s) >= MIN_DOVZHYNA]
    return dovgi[0] if dovgi else ""


def _znachennia(lines: list[str], i_fam: int | None, i_imia: int) -> list[str]:
    kand: list[str] = []
    if i_fam is not None:
        m = _FAM.search(lines[i_fam])
        zalyshok = lines[i_fam][m.end():] if m else ""
        if zalyshok and not _PIDPYSY.search(zalyshok):
            kand.append(zalyshok)
        kand.extend(ln for ln in lines[i_fam + 1:i_imia] if ln and not _PIDPYSY.search(ln))
    if not kand:
        # Інший бланк: спершу всі підписи, значення під ними — перші рядки
        # без підпису й без номера поля після «Имя».
        kand = [ln for ln in lines[i_imia + 1:]
                if ln and not _PIDPYSY.search(ln) and not _NOMER.search(ln)][:3]
    return kand


def pole_prizvyshcha(text: str) -> str:
    """Прізвище з поля бланка на лицьовому боці картки, або «».

    Повертає написання з великої літери, як прочитав рушій, — без виправлень:
    що там насправді, вирішує око на кадрі.
    """
    lines = [ln.strip() for ln in (text or "").splitlines()[:SHAPKA]]
    i_imia = next((i for i, ln in enumerate(lines[:SHAPKA_IMIA])
                   if len(ln) < 60 and _IMIA.search(ln)), None)
    if i_imia is None:
        return ""
    i_fam = next((i for i, ln in enumerate(lines[:i_imia + 1]) if _FAM.search(ln)), None)
    for k in _znachennia(lines, i_fam, i_imia):
        z = _zlyty(k)
        if (len(z) >= MIN_DOVZHYNA and not _PIDPYSY.search(z)
                and not _PO_BATKOVI.search(z) and not known_given(z)):
            return z[:1].upper() + z[1:].lower()
    return ""


def varianty(prizvyshche: str) -> list[str]:
    """Написання для покажчика: як прочитано і без першої літери.

    Друга форма — лише коли лишається ≥ `MIN_DOVZHYNA` літер (див. шапку
    модуля: перша літера на картці калічиться систематично).
    """
    p = (prizvyshche or "").strip()
    if len(p) < MIN_DOVZHYNA:
        return []
    out = [p]
    if len(p) - 1 >= MIN_DOVZHYNA:
        out.append(p[1:2].upper() + p[2:])
    return out


def zibraty_z_anket(teksty: Iterable[str]) -> Counter[str]:
    """Прізвища з полів бланка по всіх сторінках і голосах, з варіантами.

    Порожній лічильник — тексти не схожі на анкети.
    """
    out: Counter[str] = Counter()
    for t in teksty:
        p = pole_prizvyshcha(t)
        for v in varianty(p):
            out[v] += 1
    return out


def doreformenist(text: str) -> float:
    """Частка кириличних слів із дореформеними літерами й закінченнями.

    На картці 1949 року голос, навчений на метриках XIX ст., пише
    «Ольгопольскаго», «Ѳеономъ», «Святомъ» — слова з метрик, яких на картці
    немає. Ця частка — дешевий детектор такої вигадки для документа ХХ ст.;
    для документа до 1918 року вона нічого не означає.
    """
    old, words = doreformeni_slova(text)
    return old / words if words else 0.0


def doreformeni_slova(text: str) -> tuple[int, int]:
    """(дореформених слів, кириличних слів) — щоб зводити частку по сторінках."""
    slova = _KYRYLYTSIA.findall(text or "")
    return sum(1 for s in slova if _DOREFORMENI.search(s)), len(slova)
