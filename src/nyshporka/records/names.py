# Ключі й значення тримаємо ВЖЕ нормалізованими: пошук іде по виходу
# normalize_archival (латиниця), і кирилична форма в мапі просто ніколи б не
# збіглася — саме на цьому звід спершу розводив «Онисимовъ» і «Анисимовъ»
# у двох різних людей, а за ними розпадався і двір.
_TO_CANON: dict[str, str] = {}
for _canon, _vars in _ALIASES.items():
    _c = normalize_archival(_canon)
    _TO_CANON[_c] = _c
    for _v in _vars:
        _TO_CANON[normalize_archival(_v)] = _c

# Суфікси теж у латиниці — рядок сюди приходить уже після normalize_archival.
_PATR_SUFFIX = re.compile(r"(ovic|evic|ovna|evna|icna|ova|eva|ina|ov|ev|in|a)$")
# Хвостові -i/-e лишаються від «-ієвъ»/«-ьевъ»: afanasiev→afanasi, afanasev→afanas.
# Без цього зрізу дві законні форми одного по батькові не сходяться.
_PATR_TAIL = re.compile(r"[ie]+$")


def norm_given(value: str | None) -> str:
    """Канонічна форма особового імені; невідоме — просто нормалізований рядок."""
    n = normalize_archival(value or "")
    return _TO_CANON.get(n, n)


def norm_patronymic(value: str | None) -> str:
    """«Онисимовъ» / «Анисимовна» → 'anisim'; «Аѳанасіевъ» / «Афанасьевъ» → 'afanas'.

    Стать по батькові свідомо не розрізняємо: вона й так відома з ролі, а
    об'єднана основа дає збіг чоловічої й жіночої форм одного роду.
    """
    n = normalize_archival(value or "")
    if not n:
        return ""
    base = _PATR_SUFFIX.sub("", n) or n
    base = _PATR_TAIL.sub("", base) or base
    return _TO_CANON.get(base, base)


def norm_surname(value: str | None) -> str:
    """Прізвище: тільки писемність і діакритика — форми не канонізуємо,
    бо «Гончаръ» і «Ганчаръ» можуть бути різними родами; їх зближує fuzzy."""
    return normalize_archival(value or "")


def split_name(full: str) -> tuple[str, str, str]:
    """Груба розбивка сирого рядка «Стефанъ Онисимовъ Ревега» → (ім'я, по батькові, прізвище).

    Страховка на випадок, коли агент не заповнив окремі поля. Свідомо
    консервативна: два токени — це ім'я+по батькові без прізвища (найчастіший
    випадок для жінок), а не ім'я+прізвище.
    """
    toks = [t for t in re.split(r"\s+", (full or "").strip()) if t]
    if not toks:
        return "", "", ""
    if len(toks) == 1:
        return toks[0], "", ""
    if len(toks) == 2:
        return toks[0], toks[1], ""
    return toks[0], toks[1], " ".join(toks[2:])
