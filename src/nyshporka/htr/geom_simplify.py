"""📐 Беззбиткове прорідження полігонів рядків: геть точки посеред прямого відрізка.

Полігон рядка з сегментатора несе в середньому 28–39 точок, і чверть із них
стоїть посеред прямого відрізка між сусідами (замір 03.11.2026, 13,9 тис.
полігонів). Поверх gzip це ще −15 % геометрії.

🔴 Беззбитково — означає та сама МАСКА, а не лише той самий контур. Перша версія
викидала будь-яку точку на прямій і на трьох прогонах (211 506 полігонів) дала 4
маски з різницею в піксель. Причин дві, і обидві в растрі PIL, а не в геометрії:

* дубль вершини (нульовий відрізок) PIL малює інакше, ніж його відсутність;
* похилий відрізок A→C растр округлює не так, як ламану A→B→C, навіть коли B
  лежить на ньому точно (`(435,808)→(430,878)→(429,892)`).

Тому точка йде лише тоді, коли лежить СТРОГО МІЖ сусідами на горизонталі,
вертикалі чи діагоналі 45°: там растр відрізка однаковий за побудовою. Економія
від цього обмеження майже не падає (−14,6 % проти −14,7 %).

Не робимо спрощення з допуском (Дуглас — Пекер): на 2 пікселях найгірший рядок
губить 16 % площі, а маска йде в запасну нарізку кропів.

Модуль без жодного імпорту пакета: раннер на боксі має дзеркало
(`runner.drop_collinear`), збіг сторожить `tests/test_geom_simplify.py`.
"""
from __future__ import annotations

from typing import Any


def _redundant(a: Any, b: Any, c: Any) -> bool:
    """Чи точка b лишня між a і c: строго між ними на осьовому чи 45° відрізку."""
    ax, ay = a[0], a[1]
    bx, by = b[0], b[1]
    cx, cy = c[0], c[1]
    dx, dy = cx - ax, cy - ay
    if not (dx == 0 or dy == 0 or abs(dx) == abs(dy)):
        return False
    if (bx - ax) * dy - (by - ay) * dx != 0:
        return False
    # строго між сусідами: обидва відрізки ненульові й одного напряму (дубль і
    # «шпичка», де контур розвертається, лишаються)
    return (bx - ax) * (cx - bx) + (by - ay) * (cy - by) > 0 and (bx, by) != (ax, ay) \
        and (bx, by) != (cx, cy)


def drop_collinear(poly: Any) -> Any:
    """Замкнений полігон без лишніх точок; порядок і решта точок — як були."""
    if not isinstance(poly, list) or len(poly) < 4:
        return poly
    pts = list(poly)
    changed = True
    while changed and len(pts) > 3:
        changed = False
        i = 0
        while i < len(pts) and len(pts) > 3:
            if _redundant(pts[i - 1], pts[i], pts[(i + 1) % len(pts)]):
                del pts[i]
                changed = True
                if i > 0:
                    i -= 1
            else:
                i += 1
    return pts


def simplify_payload(payload: dict[str, Any]) -> dict[str, Any]:
    """Геометрія сторінки з прорідженими `polys`; решта полів — ті самі об'єкти."""
    polys = payload.get("polys")
    if not isinstance(polys, list):
        return payload
    return {**payload, "polys": [drop_collinear(p) if p else p for p in polys]}
