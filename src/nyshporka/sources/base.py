"""📥 Джерело матеріалу — один контракт на архіви, дзеркала й локальні теки.

Досі кожен архів мав власний скрипт із власними прапорцями, і жоден із них не
було видно з застосунку: вкладка «звідки взяти справу» не існувала, бо не
існувало спільної форми. Тут ця форма з'являється.

Одне джерело відповідає на чотири питання, і кожне з них опційне:

    search    «де взагалі є щось про моє село» — пошук по каталогу
    browse    «що лежить у цьому фонді» — дерево
    manifest  «що саме принесе завантаження» — скільки кадрів, який покажчик
    fetch     власне завантаження, з прогресом

🔴 Чому `manifest` окремо від `fetch`. Справа буває на кілька гігабайтів, і
питання «скільки це» мусить мати відповідь до того, як почалось качання. Без
цього єдиний спосіб дізнатись обсяг — почати й подивитись, а перервана закачка
лишає теку в невизначеному стані.

🔴 Чому `ref` непрозорий. У кожного архіву своя адресація: у ARCHIUM це номер
справи, у дзеркала плівок — ідентифікатор теки, у локальної теки — шлях.
Спроба звести їх до спільного «ключа справи» ламається на першому ж архіві з
іншою нумерацією, тож `ref` лишається рядком, який розуміє тільки те джерело,
що його видало.
"""
from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass, field
from pathlib import Path
from typing import Literal, Protocol, runtime_checkable

#: `address` — знайти справу за ШИФРОЮ, а не за текстом заголовка. Здатність
#: окрема від `search` навмисно: каталог часто вміє одне й не вміє друге —
#: зведений покажчик шукає живим запитом лише по назві, тож спитати його
#: «що це за 127-1078-1662» нічим, хоч сам він цю шифру в кожному хіті й
#: друкує. Без окремої здатності нуль такого джерела читався б як «справи
#: немає», а він означає «його про це не питали».
Capability = Literal["search", "browse", "manifest", "fetch", "address"]

#: Куди джерело звітує про поступ. Сигнатура навмисно збігається з
#: `core.progress.emit`, щоб завантаження, читання й трен виглядали однаково.
ProgressFn = Callable[..., None]


@dataclass(frozen=True)
class Hit:
    """Знахідка в каталозі — те, що показують у списку результатів."""

    source: str
    ref: str
    title: str = ""
    years: str = ""
    place: str = ""
    shifra: str = ""
    frames: int | None = None
    #: Чи можна це завантажити прямо звідси. Каталог часто знає про справу
    #: більше, ніж уміє дати: опис є, а сканів немає. Показати таку справу
    #: корисно (це відповідь «де шукати»), але обіцяти завантаження — ні.
    acquirable: bool = False
    note: str = ""
    #: Сторінка знахідки у джерела — там, де читати про неї далі.
    #: 🔴 Потрібна саме тим джерелам, які не віддають файлів: покажчик знає про
    #: справу все, крім самої справи, і без адреси його знахідка перетворюється
    #: на рядок, з яким нічого не зробиш.
    url: str = ""
    #: Архів і фонд знахідки — нашими кодами, коли джерело їх знає.
    #: 🔴 Розібрані поля, а не самий рядок шифри. Пошук по каталогах — перший
    #: крок циклу «знайти фонд → оцінити → зібрати його реєстр», і другий крок
    #: неможливий, поки фонд лишається шматком тексту всередині шифри: з десяти
    #: знахідок не видно, чи вони з одного фонду, чи з шести різних, і спитати
    #: покажчик про сам фонд теж нема чим.
    repo: str = ""
    fond: str = ""
    #: Код архіву так, як його зве саме джерело («ДАЖО», «ЦДІАК»).
    #: 🔴 Окремо від `repo`, і обидва потрібні. `repo` — наш канонічний код, і
    #: він порожній для архіву, якого немає в паку: підставлений туди чужий код
    #: завів би архів, якого ми не тримаємо, і звірка «чи є цей фонд у нас»
    #: порівнювала б його сам із собою. Але гасити через це саму назву не можна
    #: — покажчик її назвав, і «? ф.118» замість «ДАЖО ф.118» приховує рівно те,
    #: заради чого до зведеного покажчика й ідуть: архів, якого ми ще не знаємо.
    archive: str = ""
    #: Лист документа, на якому стоїть збіг, — для джерел, що шукають у ТЕКСТІ.
    #: 🔴 Окремо від `frames`: там обсяг справи, а тут місце слова в ній. Злиті
    #: в одне поле, «1252» читалось би то як «у справі 1252 кадри», то як
    #: «слово на 1252-му», і гортати довелось би навмання.
    page: int | None = None
    #: Адреса вирізки навколо слова (http/https). Картинку тягне браузер чи
    #: людина за посиланням, не ми: знахідка без кропа вимагає завантаження
    #: цілої справи лише для того, щоб побачити, чи це взагалі прізвище.
    crop_url: str = ""


@dataclass(frozen=True)
class Node:
    """Вузол дерева при перегляді джерела."""

    ref: str
    label: str
    kind: Literal["folder", "case", "file"] = "folder"
    frames: int | None = None
    size: int | None = None


@dataclass(frozen=True)
class Sheet:
    """Рядок поаркушевого покажчика: які кадри що накривають.

    🔴 Це найцінніше, що може дати джерело, і воно рідко буває. Покажчик
    відповідає «де метрики мого села» без жодного завантаження — тобто закриває
    найбільшу аудиторію одним запитом.
    """

    frm: int
    to: int
    label: str = ""


@dataclass(frozen=True)
class Manifest:
    """Що саме принесе завантаження."""

    source: str
    ref: str
    title: str = ""
    #: 🔴 `None` — «джерело не назвало числа», і це не те саме, що нуль.
    #: Поки поле було просто `int`, обидва стани злипались, і завантаження
    #: нічого не могло довести: звірка з нулем або мовчить завжди, або лається
    #: завжди. Різницю породжують самі джерела — Commons знає `pagecount` лише
    #: для багатосторінкових, локальна тека не знає сторінок PDF без читача, —
    #: тож сховати її тут означало б вигадати знаменник за них.
    #: Сусідні `Hit.frames` і `Node.frames` це вміли давно.
    frames: int | None = 0
    bytes_estimate: int | None = None
    sheets: tuple[Sheet, ...] = ()
    #: Довільні поля джерела — потраплять у сайдкар теки як є.
    meta: dict[str, object] = field(default_factory=dict)

    def frames_for(self, label_part: str) -> tuple[int, int] | None:
        """Діапазон кадрів за фрагментом підпису покажчика."""
        needle = label_part.casefold()
        for s in self.sheets:
            if needle in s.label.casefold():
                return (s.frm, s.to)
        return None


@dataclass
class FetchResult:
    """Що справді лягло на диск.

    ⚠ Тут немає властивості «успішно», і це навмисно. Вона була — `frames > 0
    and not errors`, — не мала жодного викликача й відповідала на питання, на
    яке результат сам по собі відповісти не може: повнота доводиться звіркою зі
    знаменником (`Manifest.frames`), а не відсутністю помилок. Дзеркало, що
    віддало сорок кадрів із трьохсот без жодного збою, проходило її як успіх.
    До того ж повторне завантаження вже готової теки (усе в `skipped`,
    `frames == 0`) вона оголошувала невдалим.
    """

    dest: Path
    frames: int = 0
    bytes: int = 0
    skipped: int = 0
    errors: list[str] = field(default_factory=list)
    #: Те, що людина мусить знати про взяте, але що не є збоєм завантаження:
    #: «у книги немає текстового шару», «шар битий». 🔴 Окремо від `errors`,
    #: бо помилка робить теку неповною й код виходу ненульовим — а тут файл
    #: ліг цілим, просто шукати в ньому регексом не вийде.
    notes: list[str] = field(default_factory=list)


class SourceError(RuntimeError):
    """Джерело не змогло виконати запит — із поясненням для людини."""


@runtime_checkable
class Source(Protocol):
    """Контракт джерела. Реалізація оголошує, що вміє, через `caps`.

    Незаявлена можливість не викликається; реалізовувати заглушки, які кидають
    «не підтримується», не треба — застосунок питає `caps` і не пропонує
    користувачу того, чого джерело не вміє.
    """

    id: str
    label: str
    caps: frozenset[str]

    def search(self, q: str, *, limit: int = 30) -> list[Hit]: ...

    def browse(self, ref: str | None = None) -> list[Node]: ...

    def manifest(self, ref: str) -> Manifest: ...

    def fetch(self, ref: str, dest: Path, *, frames: tuple[int, int] | None = None,
              on_progress: ProgressFn | None = None) -> FetchResult: ...


@runtime_checkable
class CaseFinder(Protocol):
    """Джерело, яке вміє `address` — знайти справу за самою лише шифрою.

    🔴 Окремо від `Source`, і це та сама домовленість, що вище: можливість
    оголошується через `caps`. Доти `find_case` стояв у спільному контракті й
    вимагав методу від УСІХ, хоч уміє його одне джерело з п'яти — тобто змушував
    писати рівно ті заглушки, яких контракт просить не писати. Мовчки це не
    минулось: чотири джерела перестали проходити перевірку типів.
    """

    def find_case(self, fond: str, opys: str, spr: str, *,
                  repo: str = "") -> list[Hit]: ...


def supports(src: object, cap: Capability) -> bool:
    return cap in getattr(src, "caps", frozenset())


#: На чому джерело шукає збіг.
#:
#:     title        заголовок справи чи назва альбому
#:     annotation   опис події, анотація справи чи твору
#:     fond_title   назва фонду
#:     fulltext     текст самого документа (OCR, текстовий шар)
#:     sheet_place  місце в поаркушевому покажчику плівки
#:     settlement   село, до якого каталог прив'язав книгу
MatchOn = Literal["title", "annotation", "fond_title", "fulltext", "sheet_place",
                  "settlement"]

#: Як звіряється слово.
#:
#:     substring   підрядок після регістру й апострофів — відмінків не знає
#:     normalized  підрядок після зведення написань (рос./укр., ё/е)
#:     exact_word  лише точне слово: інша форма, зірка чи OR — не збіг
#:     server      правило збігу тримає чужий сервер, і ми його не бачимо
MatchHow = Literal["substring", "normalized", "exact_word", "server"]


def _opt_list(v: tuple[str, ...] | None) -> list[str] | None:
    return list(v) if v is not None else None


@dataclass(frozen=True)
class SourceScope:
    """ДЕ і КОЛИ джерело взагалі може щось знати.

    🔴 `None` і `()` — різні відповіді, як у `Manifest.frames`: `None` — «джерело
    не задекларувало», `()` — «явно порожньо» (Чтиво не архівне, архівів у нього
    немає). Злиті в одне, «не сказали» читалось би як «накриває все» — і нуль
    джерела поза його регіоном виглядав би звичайним нулем.
    """

    #: Коди архівів нашого паку (`DAHMO`, `CDIAK`).
    archives: tuple[str, ...] | None = None
    #: Країни кодами паку (`UA`, `MD`).
    countries: tuple[str, ...] | None = None
    #: Роки документів (від, до); край `None` — відкритий.
    years: tuple[int | None, int | None] | None = None
    #: Жанри документів словами довідника «Куди копати».
    genres: tuple[str, ...] | None = None
    #: Межа словами — там, де числом не виходить.
    note: str = ""

    def as_dict(self) -> dict[str, object]:
        return {"archives": _opt_list(self.archives),
                "countries": _opt_list(self.countries),
                "years": list(self.years) if self.years is not None else None,
                "genres": _opt_list(self.genres), "note": self.note}


@dataclass(frozen=True)
class SourceAbout:
    """Самоопис джерела: про що воно, де його межі, що доводить його нуль.

    🔴 Навіщо в коді, а не лише в картці довідника. Агент складав маршрут із
    таблиці класів у тексті, а перелік джерел жив у реєстрі, і два списки
    розійшлись мовчки: фотоархів Волока був підключений, але без картки, тож
    правило «канал без картки в маршрут не ставиться» викинуло його з плану про
    Донеччину (симуляція 15.09.2026). Опис, що їде разом із джерелом у
    `sources.list`, від реєстру не відстане, а з карткою його звіряє тест
    `tests/test_source_cards.py`.
    """

    #: Питання, на яке відповідає, — як його ставить людина.
    answers: str
    gives: str
    not_gives: str
    #: Рядок таблиці «Класи каналів» у `where-to-dig.md` — дослівно.
    where_class: str
    scope: SourceScope
    #: Де шукає збіг. `()` — не шукає зовсім.
    match_on: tuple[MatchOn, ...]
    match_how: MatchHow | None
    #: Що доводить нуль цього джерела — одним реченням, для звіту.
    zero_means: str
    pitfalls: tuple[str, ...] = ()
    #: Ключ картки в `where-to-dig-channels.md`, коли `id` інстансний
    #: (`archium-cdiak` описаний карткою `archium`). Порожньо — сам `id`.
    card: str = ""

    def as_dict(self) -> dict[str, object]:
        return {"answers": self.answers, "gives": self.gives,
                "not_gives": self.not_gives, "where_class": self.where_class,
                "scope": self.scope.as_dict(), "match_on": list(self.match_on),
                "match_how": self.match_how, "zero_means": self.zero_means,
                "pitfalls": list(self.pitfalls), "card": self.card}


def about_of(src: object) -> SourceAbout | None:
    """Самоопис джерела або `None`, якщо його не задекларовано.

    🔴 Не поле `Source`. Протокол не має дефолтів, тож нове поле стало б
    обов'язковим для кожного стороннього плагіна, який про нього не знає. Тому
    той самий прийом, що з `catalog_source` і `search_ceiling`: `getattr`, а
    відсутність видима (`sources.list` → `undeclared`), а не мовчазна.
    """
    try:
        got = getattr(src, "about", None)
    except Exception:
        # 🔴 Властивість `about` (ARCHIUM, «Бабин Яр») читає пак архівів, а
        # `getattr` із дефолтом ловить лише `AttributeError`. Збій паку не має
        # валити пошук по ВСІХ джерелах: джерело стає «без опису» — видимо, в
        # `undeclared`, а не мовчки.
        return None
    return got if isinstance(got, SourceAbout) else None
