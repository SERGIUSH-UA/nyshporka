"""🔌 Що доступне зараз у цьому процесі.

Частина операцій має сенс лише в запущеному застосунку: черга завдань живе в
демоні, який тримає замок простору. Команда, викликана окремо, до неї не
дістанеться — і мусить сказати це прямо.

🔴 Чому не «підняти демон нишком». Тоді кожен виклик CLI ставав би другим
писарем на простір, а це рівно те, від чого захищає замок. Чесна відмова з
підказкою краща за тихе роздвоєння стану.
"""
from __future__ import annotations

from nyshporka.core.jobs import JobBus

_bus: JobBus | None = None


def set_bus(bus: JobBus | None) -> None:
    """Оголосити чергу цього процесу. Викликає застосунок на старті."""
    global _bus
    _bus = bus


def current_bus() -> JobBus | None:
    """Черга або None. None — це відповідь «застосунок не запущено»."""
    return _bus
