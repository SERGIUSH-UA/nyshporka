PARADIGMS: dict[str, Paradigm] = {
    p.id: p for p in (_ADJ_SKYI, _NOUN_OV, _NOUN_BARE, _NOUN_KO, _INDECLINABLE)}


def paradigm_ids() -> str:
    """Перелік id для довідки: «adj_skyi | noun_ov | …».

    🔴 Живе тут, бо доти той самий рядок стояв літералом у трьох місцях —
    схемі `profile.set`, довідці CLI і шаблоні скіла, — і всі три при додаванні
    парадигми мовчки застарівали. Третя до того ж їде в дистрибутиві, тобто
    застарівала б і у встановленого користувача.
    """
    return " | ".join(PARADIGMS)


def paradigm(pid: str) -> Paradigm:
    try:
        return PARADIGMS[pid]
    except KeyError:
        raise KeyError(
            f"невідома парадигма «{pid}». Є: {', '.join(sorted(PARADIGMS))}") from None


# ── переноси ─────────────────────────────────────────────────────────────────
def hyphenate(word: str, cut: int, joiner: str = " ") -> tuple[str, str, str]:
    """Слово, розірване переносом → (повний запис, голова, хвіст).

    Повертає всі три, бо в декоді вони зустрічаються окремо: голова «Доли-» на
    кінці рядка, хвіст «щинский» на початку наступного, а разом вони читаються
    лише вікном. Саме тому пошук цілого слова сліпий до переносів — 2 з 4
    прізвищ у сповідці 1846 розірвані через рядок.
    """
    if not 0 < cut < len(word):
        raise ValueError(f"розріз {cut} поза межами слова «{word}» ({len(word)} літер)")
    head, tail = word[:cut] + "-", word[cut:]
    return f"{head}{joiner}{tail}", head, tail


# ── таргети для fuzzy-пошуку ─────────────────────────────────────────────────
#: Скільки літер відрізати від голови на кожному щаблі й з якою вагою.
#: 🔴 Це generic-правило, а не властивість прізвища: рушій калічить довге слово
#: сильніше за коротке, тож повний корінь мусить конкурувати з власними хвостами.
#: Ваги дисконтують частковий збіг; береться max по щаблях (`anchor.htr_match`).
TARGET_LADDER: tuple[tuple[int, float], ...] = ((0, 1.0), (2, 0.85), (4, 0.65))
#: Голова переносу окремим таргетом: сама по собі це слабкий сигнал.
HEAD_TARGET: tuple[int, float] = (4, 0.45)


def htr_targets(root: str,
                ladder: tuple[tuple[int, float], ...] = TARGET_LADDER,
                head: tuple[int, float] | None = HEAD_TARGET,
                ) -> tuple[tuple[str, float], ...]:
    """Нормалізований корінь → драбина таргетів «корінь + його хвости».

    `root` подається вже нормалізованим (мала літера, без ѣ/ъ/ь/й) — щоб цей
    модуль не тягнув за собою нормалізатор пошуку.
    """
    out = [(root[skip:], w) for skip, w in ladder if skip < len(root)]
    if head is not None:
        n, w = head
        if n < len(root):
            out.append((root[:n], w))
    return tuple(out)
