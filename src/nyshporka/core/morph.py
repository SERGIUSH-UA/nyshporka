"""🔤 Морфологія прізвища — форми породжуються, а не переписуються руками.

Навіщо. Пошук прізвища в рукописному декоді стоїть на переліку його написань:
відмінки, роди, дореформена орфографія, польська латинка, розрив переносом.
Зібрати такий перелік руками — це десятки рядків на кожне прізвище, і саме тому
готові інструменти пошуку по архівах працюють лише з тим родом, під який їх
писали.

Тому тут генератор: **основа + парадигма → повний набір форм**. Основа — це
дані (дослідник знає, як його прізвище пишеться в російській, українській і
польській традиції), парадигма — код (7 відмінків × 2 роди × множина × 5
орфографій ≈ 70 форм, які інакше довелося б виписувати вручну).

Приклад наскрізь: «Сикорский» / «Сікорський» / «Sikorski».

🔴 Що не узагальнюється і чому саме так:

* **Основа на кожну орфографію задається явно.** Рос. «Сикор-» → укр. «Сікор-»:
  перша «и» стає «і», а «и» в закінченні лишається. Позиція залежить від історії
  слова, не від правила, тож автоматична згортка помиляється частіше, ніж
  допомагає — а ціна помилки тут мовчазна: половина написань просто не шукається.
* **Орфографія `bank` — не мова, а таблиця підписів.** Вона може бути внутрішньо
  непослідовною (наз. відмінок дореформений поруч із сучасним родовим), якщо так
  склалось історично в конкретному дослідженні: це мітки, на які вже спирається
  зроблена розмітка, і «полагодити» їх означало б тихо перетегувати її.
  Генератор відтворює таблицю як є.
* **Описки не виводяться.** Те, як помиляється писар (зайвий м'який знак,
  переставлені літери), правилом не породжується; такі форми лишаються явним
  переліком у профілі дослідження.
"""
from __future__ import annotations

from dataclasses import dataclass, field

#: Порядок відмінків — він же порядок підписів у банку розмітки.
CASES: tuple[str, ...] = ("nom", "gen", "dat", "acc", "ins", "loc", "voc")
GENDERS: tuple[str, ...] = ("m", "f")

#: Орфографічні шари. `bank` — не мова, а історична таблиця підписів (див. докстрінг).
ORTHOGRAPHIES: tuple[str, ...] = ("bank", "ru_modern", "ru_prereform", "uk", "pl")


@dataclass(frozen=True)
class Paradigm:
    """Закінчення на кожну орфографію. Основа підставляється зліва."""

    id: str
    label: str
    #: орфографія → код форми («nom_m», «gen_f», «gen_p») → закінчення
    endings: dict[str, dict[str, str]] = field(default_factory=dict)
    #: Чи парадигма перевірена на живому матеріалі, чи лише заготовка.
    verified: bool = False

    def form(self, stem: str, code: str, orth: str = "bank") -> str | None:
        table = self.endings.get(orth)
        if table is None or code not in table:
            return None
        return stem + table[code]

    def forms(self, stem: str, orth: str = "bank") -> dict[str, str]:
        table = self.endings.get(orth) or {}
        return {code: stem + end for code, end in table.items()}


