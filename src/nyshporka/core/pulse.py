"""💓 Пульс простору — «щось у даних змінилось», без опитування диска.

**Навіщо.** Реєстр справ мусить знати, чи він відстав від джерел. Досі відповідь
добувалась опитуванням: два `glob` і ~840 `stat()` на кожен HTTP-запит двох
вкладок консолі. Ціна вердикту не має залежати від того, скільки разів його
спитали за секунду.

Тут — мітка, яка змінюється на кожній операції, що ЩОСЬ МІНЯЄ. Збірка реєстру
запам'ятовує її; розбіжність означає «точно застарів», і це знання коштує один
`stat` замість восьмисот.

🔑 **Мітка — це `st_mtime_ns` самого файла, а не лічильник усередині нього.**
Лічильник довелося б читати, збільшувати й записувати, тобто два процеси (консоль
і CLI, дві агентські сесії) губили б удари одне одного — а загублений удар
означає «реєстр свіжий» там, де він застарів, тобто помилку в НЕБЕЗПЕЧНОМУ
напрямку. Час зміни файла такої вади не має за побудовою: хто б не писав
останнім, мітка все одно відрізняється від запам'ятованої, і замок не потрібен
узагалі. Тіло файла лишається людським поясненням («хто вдарив і чому»), і його
неточність під гонкою нічого не ламає.

🔴 **Межа, яку треба назвати вголос: пульс знає лише про зміни ЧЕРЕЗ застосунок.**
Файл, скопійований у `data/raw` через Провідник, пульсу не б'є. Тому

    пульс має право сказати «застарів» швидко,
    але НІКОЛИ не має права сказати «свіжий» напевно.

Саме тому він не заміщає повну перевірку, а лише знімає її з шляху запиту:
збіг мітки — привід зробити ДЕШЕВУ перевірку, а не привід її пропустити.

**Хто б'є.** Одне місце — `core.ops.Registry.call()` після кожної успішної
операції з `mutates=True`. Це вже єдиний диспетчер для CLI, HTTP і MCP, тож
правити операції не треба й забути неможливо за побудовою. Робота повз реєстр
(раннер HTR, скрипти дослідницького конвеєра) б'є явним викликом `beat()`.
"""
from __future__ import annotations

import json
import os
import time
from pathlib import Path
from typing import Any

#: Ім'я файла в `data/derived`. З крапки — це службовий стан, не дані дослідження.
PULSE_NAME = ".pulse.json"

#: Значення мітки, коли пульсу немає (простір щойно створено, запис не вдався).
#: Нуль, а не `None`: він порівнюється так само, як будь-яка інша мітка.
NO_PULSE = 0


def pulse_path() -> Path:
    from nyshporka.core.workspace import workspace

    return workspace().derived / PULSE_NAME


def seq() -> int:
    """Поточна мітка (`st_mtime_ns` файла пульсу). Один системний виклик."""
    try:
        return pulse_path().stat().st_mtime_ns
    except (OSError, Exception):
        return NO_PULSE


def snapshot() -> dict[str, Any]:
    """Мітка + людське пояснення останнього удару: `{seq, at, by, what}`."""
    out: dict[str, Any] = {"seq": seq(), "at": "", "by": "", "what": ""}
    try:
        raw = json.loads(pulse_path().read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return out
    if isinstance(raw, dict):
        out.update({"at": str(raw.get("at") or ""), "by": str(raw.get("by") or ""),
                    "what": str(raw.get("what") or "")})
    return out


def beat(by: str, what: str = "") -> int:
    """Позначити, що дані змінились. Повертає нову мітку (0, якщо не вдалось).

    Невдача запису НЕ є помилкою виклику: пульс — прискорювач, і застосунок
    мусить працювати без нього. Але тоді він мовчить, а не бреше: мітка
    лишається старою, тож вердикт «застарів» просто прийде з повної перевірки.
    """
    try:
        path = pulse_path()
        path.parent.mkdir(parents=True, exist_ok=True)
        payload = {"at": time.strftime("%Y-%m-%dT%H:%M:%S"),
                   "by": str(by), "what": str(what)}
        # 🔴 Запис через тимчасовий файл + `replace`: читач ніколи не має
        # побачити половину JSON. `replace` оновлює й час зміни, тобто саму мітку.
        tmp = path.with_name(path.name + f".{os.getpid()}.tmp")
        tmp.write_text(json.dumps(payload, ensure_ascii=False), encoding="utf-8")
        os.replace(tmp, path)
        return path.stat().st_mtime_ns
    except Exception:
        return NO_PULSE
