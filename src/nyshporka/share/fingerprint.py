"""🔎 Відбиток зйомки: чи це ті самі кадри.

Задача вузька. Той самий архівний том знімали двічі, ту саму зйомку качали
вп'ятьох і кожен розбирав PDF своїм інструментом — і питання «це та сама
зйомка чи інша» вирішує, чи ляжуть чужі координати рядків на ваші пікселі.
Помилитись тут дорожче, ніж не відповісти: чужа геометрія ріже кроп із
порожнього поля, і виглядає це як «пустий скан», а не як помилка прив'язки.

Що саме беремо
--------------

П'ять кадрів на частках 10/30/50/70/90 % і кількість кадрів. Не перший і
останній, хоч так і здається природним, — з двох причин:

* **перекодування.** Зйомка ходить у мережі як PDF, а на сторінки її
  розбирає кожен своїм інструментом; байти після цього різні в усіх;
* **обкладинки.** Перший і останній аркуш найчастіше порожні або є
  заглушкою сервісу. Дві порожні обкладинки різних книг дають однаковий
  нормалізований хеш, і система впевнено скаже «та сама зйомка» на чужій
  книзі.

Два канали на кадр
------------------

**sha256 байтів** — швидкий шлях. Збігся — питань немає. Але ламається від
будь-якого дотику: `cloud/frames.shrink` міняє формат, колір, розмір і
якість, тож на кадрах, що пройшли хмарний шлях, він не збігається ніколи.

**Різницевий хеш** — той, що переживає перекодування, бо зберігає не
значення пікселів, а їх ПОРЯДОК: стискання зсуває яскравість, але не
міняє, який піксель темніший за сусіда.

🔴 Замір на справжньому скані (1604×2568, метрична книга):

    перекодування              різницевий хеш    sha256 нормалізованого
    JPEG q95                   0 бітів різниці   не збігається
    JPEG q60                   0 бітів           не збігається
    ресайз до 50 % + q85       0 бітів           не збігається
    🔴 СУСІДНІЙ аркуш книги    69 бітів (48 %)   не збігається

Тобто «сірий → зменшити → sha256», яке здається очевидним рішенням, не
спрацьовує НІКОЛИ — воно ламається вже на перезбереженні, тобто рівно на
тому, заради чого другий канал і потрібен. Тому хешується порядок.

Ціна
----

30 мс на кадр, п'ять кадрів — частка секунди, ~30 МБ читання. Це важливо
сказати вголос, бо сусідній `align.frames_of` не рахує хешів за
замовчуванням і пояснює чому: на справі в 3772 кадри це кілька гігабайтів.
До п'яти кадрів той аргумент не застосовний.
"""
from __future__ import annotations

import hashlib
from pathlib import Path
from typing import Any

from nyshporka.share.align import frames_sorted

#: Частки, на яких беруться кадри. П'ять — стільки ж, скільки перевіряє
#: `htr/seg.py` перед прогоном, і з тієї самої причини: розбіжність є
#: властивістю ТЕКИ, а не окремого кадру, тож перший же промах її показує.
POSITIONS = (0.10, 0.30, 0.50, 0.70, 0.90)

#: Версія правила. Міняється разом із позиціями, розміром сітки або
#: нормалізацією — інакше відбитки різних правил мовчки порівнювались би
#: між собою й ніколи не збігались.
FP_VERSION = 1

#: Сітка різницевого хеша: 13×12 → 144 біти. Ширина на одиницю більша за
#: висоту, бо кожен біт — це порівняння пікселя з правим сусідом.
GRID = 12

#: Скільки бітів може розійтись і це все ще той самий кадр.
#:
#: 🔴 Не нуль, і це виміряно, а не обережність. Замір на трьох матеріалах:
#:
#:     матеріал                       кодер      своє (макс)  чуже (мін)  запас
#:     справжній скан 1604×2568       Pillow        2 біти      71 біт     69
#:     синтетика з товстим штрихом    Pillow        8 бітів     53 біти    45
#:     ДАХмО 315-1-1, три аркуші      ffmpeg        4 біти      31 біт     15
#:
#: «Своє» — та сама сторінка після q75/q45, ресайзу до 33 %, зміни
#: контейнера й повороту. «Чуже» — СУСІДНІЙ аркуш тієї самої книги, тобто
#: найсхожіше, що взагалі трапляється.
#:
#: 🔴 Третій рядок важливіший за перші два, і з двох причин.
#:
#: Перша: кодер ЧУЖИЙ. Перші два заміри робились Pillow — тією самою
#: бібліотекою, якою рахується хеш, тобто перевіряли наш код проти нашого ж.
#: Реальні копії перекодовують сканери архівів, FamilySearch і конвертери в
#: телефоні. На libjpeg-turbo (`-q:v 5`, розмір упав на третину) «своє»
#: лишилось на 0–4 бітах — канал чужий кодер переживає.
#:
#: Друга: «чуже» на ЖИВИХ сканах удвічі ближче, ніж на тому матеріалі, де
#: міряли спершу — 31 біт проти 71. Сусідні аркуші справжньої справи схожі
#: більше, ніж синтетика. Шістнадцять усе ще вдвічі менше за 31, тож число
#: правильне, але запас — 15 бітів, а не 55. Піднімати поріг заради дуже
#: побитих копій можна лише до 24; за ними починається територія, де
#: сусідній аркуш тієї самої книги стає «тим самим кадром», і кроп ріже
#: чужий рядок, не кажучи про це.
#:
#: Точна рівність тут не годиться: навіть перезбереження в PNG без утрат
#: зсуває кілька бітів, бо ресемплінг не зобовʼязаний давати той самий
#: піксель. Мітка `exact` при точній рівності не спрацьовувала б на
#: більшості справжніх пар.
MAX_DISTANCE = 16


def _dhash(im: Any) -> str:
    """Різницевий хеш зображення: 144 біти в шістнадцятковому вигляді."""
    small = im.convert("L").resize((GRID + 1, GRID), _resample())
    px = small.load()
    bits = 0
    for y in range(GRID):
        for x in range(GRID):
            bits = (bits << 1) | (1 if px[x, y] > px[x + 1, y] else 0)
    return f"{bits:0{GRID * GRID // 4}x}"


def _resample() -> Any:
    from PIL import Image

    return Image.Resampling.LANCZOS


def _normalized(path: Path) -> Any:
    """Відкрити кадр так, щоб дві копії однієї зйомки збіглися.

    🔴 Орієнтація зводиться до книжкової. `cloud/frames.shrink` розвертає
    горизонтальні кадри на 90° перед стисканням — замір там же каже 706
    кадрів із 711 в одній партії. Без цього хеш не збігався б саме в
    найчастішому випадку: оригінал на боці проти хмарної копії, поставленої
    сторч.

    `draft` просить декодер JPEG віддати одразу зменшене зображення — це
    DCT-скейлінг усередині декодера, у рази дешевший за повний декод із
    наступним ресайзом. На інших форматах просто не діє.
    """
    from PIL import Image

    opened = Image.open(path)
    opened.draft("L", (256, 256))
    opened.load()
    im: Any = opened
    if im.width > im.height:
        im = im.transpose(Image.Transpose.ROTATE_270)
    return im


def _sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def positions_for(total: int) -> list[int]:
    """Номери кадрів (1-based), які лягають у відбиток.

    На короткій справі частки сходяться в один кадр — тоді беремо стільки
    різних, скільки є. Відбиток із трьох слотів чесніший за відбиток із
    п'яти, де три однакові: збіг такого «п'ятірного» відбитка доводив би
    менше, ніж заявляв.
    """
    if total <= 0:
        return []
    out: list[int] = []
    for at in POSITIONS:
        n = min(total, max(1, round(total * at)))
        if n not in out:
            out.append(n)
    return out


def fingerprint(case_dir: Path, *, frames: list[Path] | None = None) -> dict[str, Any]:
    """Відбиток зйомки в теці.

    Повертає `{"version", "frames", "slots": [...]}`. Кожен слот — або пара
    хешів, або причина, чому їх немає.

    🔴 Слот, який не дав хеша, лишається порожнім і НЕ зараховується. Це
    дослівний повтор знахідки рев'ю 21.09 у `htr/seg.py`: там п'ять кадрів
    без розміру в сайдкарі вичерпували вибірку, і головний запобіжник
    модуля казав «усе гаразд», не звіривши жодного разу. Тут та сама форма
    помилки коштувала б мітки «та сама зйомка», виданої без жодного
    порівняння.
    """
    paths = frames if frames is not None else frames_sorted(case_dir)
    total = len(paths)
    slots: list[dict[str, Any]] = []

    for i, n in enumerate(positions_for(total)):
        path = paths[n - 1]
        slot: dict[str, Any] = {"at": POSITIONS[i], "n": n, "name": path.name}
        try:
            with _normalized(path) as im:
                slot["phash"] = _dhash(im)
            slot["sha256"] = _sha256(path)
        except Exception as exc:
            # Порожній слот із причиною. Саме причина, а не мовчазний
            # пропуск: інакше «нічого не звірено» виглядає як «звірено й
            # збіглось».
            slot["why"] = str(exc)[:120] or "кадр не відкрився"
        slots.append(slot)

    return {"version": FP_VERSION, "frames": total, "slots": slots}


def checked(fp: dict[str, Any]) -> int:
    """Скільки слотів справді дали хеш."""
    return sum(1 for s in fp.get("slots") or [] if s.get("phash"))


def compare(ours: dict[str, Any], theirs: dict[str, Any]) -> tuple[int, int]:
    """Скільки слотів збіглося і скільки взагалі можна було звірити.

    Порівнюються слоти на ТИХ САМИХ частках, а не по порядку: якщо в одного
    відбитка слот порожній, він не зсуває решту.

    Збігом вважається будь-який із двох каналів — байтовий хеш або
    різницевий. Перший точний і безкоштовний, другий стійкий до
    перекодування; разом вони покривають і недоторкану копію, і перебиту.
    """
    if ours.get("version") != theirs.get("version"):
        return 0, 0
    mine = _slots(ours)
    others = _slots(theirs)
    spilni = mine.keys() & others.keys()
    zbihlos = sum(1 for at in spilni if _same(mine[at], others[at]))
    return zbihlos, len(spilni)


def _slots(fp: dict[str, Any]) -> dict[float, dict[str, Any]]:
    """Слоти, які можна звіряти. Чужий відбиток — дані від незнайомця.

    🔴 Слот не того вигляду (не словник, без частки, хеш не рядок) просто не
    звіряється: доти `slots: ["x"]` чи `phash: 5` валили прийняття сирим
    винятком замість того, щоб чесно сказати «звірити нічого».
    """
    out: dict[float, dict[str, Any]] = {}
    raw = fp.get("slots")
    if not isinstance(raw, list):
        return out
    for s in raw:
        if not isinstance(s, dict) or not isinstance(s.get("phash"), str):
            continue
        at = s.get("at")
        if isinstance(at, bool) or not isinstance(at, (int, float)):
            continue
        out[float(at)] = s
    return out


def required(frames: int) -> int:
    """Скільки слотів мусять звіритись, щоб мітка `exact` щось означала.

    Один збіглий кадр доводить лише, що один кадр той самий: чужий відбиток
    з одним заповненим слотом давав `exact` «1 з 1». Потрібно три — або всі,
    що взагалі можливі на короткій справі.
    """
    return min(3, len(positions_for(frames))) if frames > 0 else 3


def _same(a: dict[str, Any], b: dict[str, Any]) -> bool:
    """Чи це той самий кадр."""
    if isinstance(a.get("sha256"), str) and a.get("sha256") and a["sha256"] == b.get("sha256"):
        return True
    return distance(str(a["phash"]), str(b["phash"])) <= MAX_DISTANCE


def distance(a: str, b: str) -> int:
    """Скільки бітів розходиться між двома різницевими хешами."""
    try:
        return bin(int(a, 16) ^ int(b, 16)).count("1")
    except ValueError:
        return GRID * GRID
