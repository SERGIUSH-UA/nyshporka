"""Текстові утиліти: slug, нормалізатори."""

from __future__ import annotations

import re

from unidecode import unidecode


def slugify(s: str) -> str:
    """Канонічний URL-friendly slug: ASCII lowercase з тире.

    Кирилиця транслітерується через `unidecode` (Сікорський → Sikorskyi).
    Усе, що не [a-z0-9] — заміняється тире, послідовності тире зливаються.
    """
    ascii_text = unidecode(s).lower()
    slug = re.sub(r"[^a-z0-9]+", "-", ascii_text).strip("-")
    return slug


# ── мішане письмо ────────────────────────────────────────────────────────────
# 🔴 Кирилиця й латинка мають десятки літер, які на екрані НЕ ВІДРІЗНИТИ:
# «ДАКО» з латинською «K» виглядає точно як «ДАКО» з кириличною. Шифри й назви
# архівів люди копіюють із сайтів архівів, з Word і з листів, а там мішане
# письмо буденна річ. Наслідок був глухий: слово не знаходилось у словнику
# архівів, і відмова друкувала введений рядок — тобто людина читала «з «ДАКО»
# не видно архіву» під написом «ДАКО», який вона щойно ввела правильно.
# (звіт користувача 29.08.2026: справа не заводилась узагалі).

#: Невидимі символи, які приносить копіювання з вебсторінок і документів.
#: Довжину рядка вони міняють, а вигляд — ні, тож збіг ламають мовчки.
INVISIBLE = "\u200b\u200c\u200d\u2060\ufeff\u00ad"  # ZWSP·ZWNJ·ZWJ·word-joiner·BOM·soft-hyphen

#: Пари, які на екрані НЕ ВІДРІЗНИТИ: латинська велика → кирилична велика.
#: ⚠ «N» сюди не входить: кирилична «Н» схожа на латинську «H», а не на «N».
_CONFUSABLE = {
    "A": "А", "B": "В", "C": "С", "E": "Е", "H": "Н", "I": "І", "J": "Ј",
    "K": "К", "M": "М", "O": "О", "P": "Р", "S": "Ѕ", "T": "Т", "X": "Х",
    "Y": "У",
}

#: 🔴 Рядкові виводяться з великих, а не виписуються поруч. Зведення кличеться
#: ПІСЛЯ `casefold()`, тобто на рядковому слові, — і виписаний окремо перелік
#: розійшовся б із великими мовчки, лишивши рівно ту глуху відмову, проти якої
#: все це написано (саме так «ДАКО» з латинською «K» не лікувалось першою
#: редакцією цієї правки: «K» у мапі був, «k» — ні).
_LAT_TO_CYR = str.maketrans({**_CONFUSABLE,
                             **{k.lower(): v.lower()
                                for k, v in _CONFUSABLE.items()}})

_CYR = re.compile(r"[Ѐ-ӿ]")
_LAT = re.compile(r"[A-Za-z]")


def strip_invisible(s: str) -> str:
    """Прибрати символи нульової ширини. Решту тексту не чіпає."""
    return "".join(ch for ch in str(s or "") if ch not in INVISIBLE)


def is_mixed_script(s: str) -> bool:
    """Чи в слові є літери ОБОХ абеток — кириличної й латинської."""
    return bool(_CYR.search(s or "")) and bool(_LAT.search(s or ""))


def fold_homoglyphs(s: str) -> str:
    """Латинські двійники → кирилиця. Для слів, де письмо переплуталось.

    🔴 Кликати ЛИШЕ після того, як точний збіг не вдався, і лише на мішаному
    слові (`is_mixed_script`). На чистій латинці це зруйнувало б справжні
    латинські коди (`DAHMO`, `ANRM`), які в словниках є самі по собі.
    """
    return str(s or "").translate(_LAT_TO_CYR)


def latin_letters_in(s: str) -> list[str]:
    """Латинські літери слова — щоб НАЗВАТИ їх людині у відмові.

    Без цього повідомлення описує стан, якого не існує: на екрані стоїть
    візуально правильне слово, а програма каже, що не впізнала його.
    """
    seen: list[str] = []
    for ch in str(s or ""):
        if _LAT.fullmatch(ch) and ch not in seen:
            seen.append(ch)
    return seen
