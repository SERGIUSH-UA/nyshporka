"""Транслітерація pl↔uk↔ru для matching.

Не намагаємось бути 100% точними фонетично — мета зробити поверхневу
нормалізацію так, щоб `rapidfuzz.WRatio` бачив схожість між варіантами
одного й того ж прізвища/імені у різних кириличних і латинських формах.

Стратегія normalize_for_matching:
1. lowercase
2. замінити польські діакритики на наближення (ń → n, ł → l, ż → z, ...)
3. замінити кириличні літери на ASCII через ru/uk-orient таблицю
4. видалити м'який знак (нечутливий до писемності)
5. стандартизувати whitespace
"""

from __future__ import annotations

import re

# Польські + румунські діакритики → ASCII. Свідомо ó→u (історично читається
# як «у»), щоб зблизити з кириличним «у» (Wójcik↔Вуйцик). Румунські ș/ț/ă/â/î
# → s/t/a/a/i, бо бессарабські метрики пишуть те саме прізвище то кирилицею, то
# румунською латинкою (`Sicorschi` ↔ «Сікорський»).
_PL_DIACRITICS = str.maketrans(
    {
        "ą": "a", "ć": "c", "ę": "e", "ł": "l", "ń": "n",
        "ó": "u", "ś": "s", "ż": "z", "ź": "z",
        "Ą": "a", "Ć": "c", "Ę": "e", "Ł": "l", "Ń": "n",
        "Ó": "u", "Ś": "s", "Ż": "z", "Ź": "z",
        "ș": "s", "ş": "s", "ț": "t", "ţ": "t",
        "ă": "a", "â": "a", "î": "i",
        "Ș": "s", "Ş": "s", "Ț": "t", "Ţ": "t",
        "Ă": "a", "Â": "a", "Î": "i",
    }
)

# PL/RO-диграфи → 1 літера. Свідомо лоссова стратегія, бо рядок піде через
# rapidfuzz і нам цікаво уніфікувати з кирилицею (де щ→sc, ч→c, ш→s).
# Порядок важливий: spec'ific перед загальним. `szcz` → `sc` обробляємо
# першим, потім `sz`/`cz` поодинці. `schi/sche` — румунський хвіст
# слов'янських прізвищ (-ський → -schi), приводимо до `ski/ske` ДО
# обробки `ch`, інакше зник `c` і отримаємо `shi`.
_PL_DIGRAPHS = (
    ("szcz", "sc"),
    ("sz", "s"),
    ("cz", "c"),
    ("rz", "r"),
    ("schi", "ski"),
    ("sche", "ske"),
    ("ghe", "ge"),
    ("ghi", "gi"),
    ("ch", "h"),
)

# Кирилиця (uk + ru) → ASCII. Свідомо ближче до польських digraphs після
# спрощення: щ→sc, ш→s, ч→c, г→g (для зближення з PL `g`).
_CYR_MAP = {
    "а": "a", "б": "b", "в": "v", "г": "g", "ґ": "g", "д": "d",
    "е": "e", "є": "e", "ё": "e", "ж": "z", "з": "z",
    "и": "i", "і": "i", "ы": "i", "ї": "i", "й": "i",
    "к": "k", "л": "l", "м": "m", "н": "n", "о": "o",
    "п": "p", "р": "r", "с": "s", "т": "t",
    "у": "u", "ф": "f", "х": "h",
    "ц": "c", "ч": "c", "ш": "s", "щ": "sc",
    "ъ": "", "ь": "", "э": "e", "ю": "u", "я": "a",
}


# Історичні літери, які _CYR_MAP не покриває, + частотні плутанини рушія
# розпізнавання на архівному матеріалі (заміряно на нотаріальній книзі XIX ст.:
# g→q/9, o→0). Це єдине місце, де визначено, що дореформене, сучасне й
# латинізоване написання одного прізвища вважаються тим самим словом; цим
# користуються і пошук по декоду, і сховище прочитаних сторінок.
_ARCHIVAL_FOLD = str.maketrans({
    "ѣ": "e", "ѳ": "f", "ѵ": "i", "ѕ": "z", "ѡ": "o", "є": "e", "ї": "i",
    "q": "g", "9": "g", "0": "o",
})


def normalize_archival(s: str) -> str:
    """normalize_for_matching + фолд історичних літер і Kraken-плутанин."""
    return normalize_for_matching(s).translate(_ARCHIVAL_FOLD)


def normalize_for_matching(s: str) -> str:
    """Перетворити рядок у поверхневий ASCII для fuzzy-порівняння.

    Стратегія — звузити обидві варіанти (PL latin + cyrillic) до спільної
    мінімальної ASCII форми, де щ↔szcz↔sc, ш↔sz↔s, ч↔cz↔c тощо.
    """
    if not s:
        return ""
    s = s.lower().translate(_PL_DIACRITICS)
    for src, dst in _PL_DIGRAPHS:
        s = s.replace(src, dst)
    # latin y → i: уніфікує з кириличним й (Yuriy↔Юрій → uri↔urii).
    s = s.replace("y", "i")
    out = [_CYR_MAP.get(ch, ch) for ch in s]
    result = "".join(out)
    # latin W ↔ V (Polish wójcik → vuitsik), нормалізуємо до v.
    result = result.replace("w", "v")
    result = re.sub(r"\s+", " ", result).strip()
    return result
