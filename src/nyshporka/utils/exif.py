"""Кадр, знятий догори ногами, з міткою EXIF `Orientation = 3`.

🔴 Замовна зйомка архіву приходить так цілими справами (ЦДІАК 442-88-271а,
442-300-2, листопад 2026): пікселі лежать догори ногами, а людина цього не
бачить, бо переглядач повертає кадр за міткою. Рушій мітки не читає, а
власний пошук орієнтації пробує лише 0/90/270 — тож справа читалась догори
ногами й давала сміття без жодної помилки. Стискач хмари мітку губив, не
повернувши пікселів, і кроп різав сирий кадр за рамками повернутої копії.

Тому всі, хто бачить кадр замість рушія або поруч із ним — стискач хмари,
кроп і перегляд сторінки, — повертають такий кадр однаково, на 180°.

⚠ Лише `3`. Мітки 6/8 (поворот на 90°) тут свідомо не чіпаються: з ними
рушій справляється сам перебором 90/270, кут пише в мету прогону (`orient`),
і кроп повертає сирий кадр на цей кут. Застосувати 6/8 ще й тут означало б
повернути двічі вже прочитані справи.
"""
from __future__ import annotations

from typing import Any

#: Тег EXIF `Orientation`.
ORIENTATION_TAG = 0x0112
#: Значення «догори ногами» (поворот на 180°).
UPSIDE_DOWN = 3


def is_upside_down(im: Any) -> bool:
    """Чи несе відкритий кадр мітку «догори ногами». Читає лише заголовок."""
    try:
        return int(im.getexif().get(ORIENTATION_TAG, 1) or 1) == UPSIDE_DOWN
    except Exception:       # битий EXIF — не наша справа тут, кадр лишаємо як є
        return False


def upright(im: Any, flip: bool) -> Any:
    """Повернути на 180°, якщо `flip`; інакше той самий об'єкт."""
    if not flip:
        return im
    from PIL import Image

    return im.transpose(Image.Transpose.ROTATE_180)
