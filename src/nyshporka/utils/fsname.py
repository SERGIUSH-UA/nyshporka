"""Ім'я файла з ЧУЖИХ рук → те, що можна класти на диск як є.

🔴 Імена кадрів приходять із мережі: дерево регіону на дзеркалі плівок, назва
файла на Commons, рядок реєстру. Кожне з них ставало компонентом шляху запису
без перевірки, тобто `..\\..\\x` або `C:\\x` у чужому JSON записав би тіло
відповіді туди, куди скаже сервер. Одна функція на всі джерела — щоб гард не
розходився між ними.
"""
from __future__ import annotations

import re

#: Символи, яких не буває в чесному імені кадру, а в шляху вони — роздільники
#: або керівні (Windows: `\\ : * ? " < > |`, обидві ОС: `/` і NUL).
_BAD = re.compile(r'[\\/:*?"<>|\x00-\x1f]')

#: Зарезервовані імена Windows: `CON.jpg` теж не створюється.
_RESERVED = re.compile(r"^(?:con|prn|aux|nul|com[1-9]|lpt[1-9])(?:\.|$)", re.I)

#: Стеля довжини одного компонента на NTFS/ext4.
_MAX = 200


class UnsafeName(ValueError):
    """Ім'я не годиться для запису на диск — з причиною для людини."""


def safe_filename(name: object) -> str:
    """Повернути ім'я, якщо воно безпечне як ОДИН компонент шляху; інакше — виняток.

    Не «полагодити», а відмовити: полагоджене ім'я розійшлося б із тим, що
    сервер віддає далі, і повторне завантаження не впізнало б файл як наявний.
    """
    s = str(name or "")
    if not s or s != s.strip() or s in (".", ".."):
        raise UnsafeName(f"порожнє або службове ім'я файла «{s}»")
    if _BAD.search(s):
        raise UnsafeName(f"ім'я файла «{s}» містить роздільник шляху або керівний символ")
    if _RESERVED.match(s):
        raise UnsafeName(f"«{s}» — зарезервоване ім'я Windows")
    if len(s) > _MAX:
        raise UnsafeName(f"ім'я файла довше за {_MAX} символів")
    return s
