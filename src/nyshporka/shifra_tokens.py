"""Три цеглинки шифри — фонд/опис/справа — без жодних побічних дій на імпорті.

🔴 Винесено з `library.py` (issue #21, CI «ставиться з нуля» падав). `library.py`
на рівні модуля виконує `_WS = workspace()` — тобто вимагає наявного робочого
простору вже при імпорті. `fonds/registry.py` бере `FOND_TOKEN` на рівні
модуля (він живе всередині `re.compile`), і раніше брав його з `library`, тож
сам імпорт `nyshporka.fonds.registry` (а через нього — `nyshporka.cli`) почав
вимагати простору відразу після встановлення, ще до першої команди.

Ці три рядки — прості константи без жодної залежності, тож їм можна дати
окремий модуль без побічних дій і брати звідти напряму, не чіпаючи `library`
на рівні модуля. `library.py` імпортує їх звідси й ре-експортує — для решти
коду пакета нічого не змінюється.
"""
from __future__ import annotations

#: 🔴 ТРИ ЦЕГЛИНИ, з яких складаються ОБИДВА розбори шифри — і той, що шукає її
#: в тексті (`library._SHIFRA_RE`), і той, що приймає людський запис
#: (`cases.register`). Доти кожен ніс власне визначення того, як виглядає
#: номер, і вони розійшлись: бібліотека навчилась читати «Р-6129», а
#: реєстрація на тій самій шифрі казала «не розібрав». Розбори різні за
#: призначенням і зводити їх в один не можна, а от відповідь на питання «що
#: таке номер фонду» мусить бути одна.
FOND_TOKEN = r"(?:[А-ЯЄІЇҐA-Z]{1,2}-)?\d+"      # 315 · Р-6129 · R-6129
OPYS_TOKEN = r"\d+[а-яa-z]?"                     # 1 · 24 · 4б
SPR_TOKEN = r"\d+[а-яa-z]?"                      # 8433 · 2а
