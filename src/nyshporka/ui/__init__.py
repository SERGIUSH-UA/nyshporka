"""🎨 Спільний шар обох морд: токени, примітиви, значки, компоненти.

Нишпорку показують двома вікнами: цим застосунком (`nysh serve`) і консоллю
приватного конвеєра, який стоїть на тому самому ядрі. Досі кожне мало власний
фронт — 1 547 рядків проти 12 152, — і розходились вони не лише обсягом: одна
знала розчеплений акцент, ярус поверхонь, спрайт значків і ручний перемикач
теми, друга не знала нічого з цього. Копіювати те, що більше, у те, що менше,
означало б завести ту саму тиху розбіжність, від якої заведено `brand.yaml`;
тому спільне переїхало сюди, а кожна морда лишила собі тільки СВОЄ.

    static/tokens.css   ⚠ ЗГЕНЕРОВАНО з brand.yaml (`python -m nyshporka.brand.gen`)
    static/base.css     примітиви: значки, розкладка, контролі, кнопки, рух
    static/theme.js     тризначна тема: авто · світла · темна
    static/dom.js       підміна вмісту без стрибка сторінки, скелетони
    static/icons.js     `ic()` — значок у своєму тоні; `eng()` — бейдж рушія
    static/combobox.js  випадний список замість нестилізовного <datalist>
    static/stage.js     спільне ядро canvas-переглядачів: зум, панорама, малювання
    data/icons.svg      спрайт значків

🔴 Спрайт віддається ФУНКЦІЄЮ, а не файлом зі `static/`, і це не забаганка:
`<use href>` до зовнішнього SVG забороняє успадкування `currentColor` у Chrome —
значки стали б чорними на будь-якому тлі. Тому він інжектується в HTML замість
`{{SPRITE}}`, і обидві морди роблять це там, де вже роблять свої підстановки.
"""
from __future__ import annotations

from functools import lru_cache
from pathlib import Path

ROOT = Path(__file__).resolve().parent
STATIC = ROOT / "static"
DATA = ROOT / "data"

#: Плейсхолдер, на місце якого стає спрайт. Однаковий в обох мордах, щоб
#: підстановка описувалась один раз.
SPRITE_SLOT = "{{SPRITE}}"


def static_dir() -> Path:
    """Тека, яку монтують обидві морди (у нас — на префікс `/ui`)."""
    return STATIC


@lru_cache(maxsize=1)
def sprite() -> str:
    """Розмітка спрайта — рівно те, що вставляється в тіло сторінки.

    Кешується: файл не змінюється за життя процесу, а вставляється він у КОЖНУ
    віддачу сторінки.

    ⚠ Відсутній файл дає ПОРОЖНІЙ спрайт, а не виняток. Це той самий принцип,
    що й у `with_sprite`: значки — косметика, і падати через них означало б не
    відкрити сторінку взагалі. Неповна установка помітна одразу (сторінка без
    жодного значка), а приймач стереже, що у власному дереві файл на місці.
    """
    try:
        return (DATA / "icons.svg").read_text(encoding="utf-8")
    except OSError:
        return ""


def with_sprite(html: str) -> str:
    """Підставити спрайт у сторінку.

    ⚠ Мовчить, якщо плейсхолдера немає: сторінка без значків лишається
    робочою, а падіння тут поклало б застосунок цілком через косметику.
    Що плейсхолдер на місці, доводить приймач, а не рантайм.
    """
    return html.replace(SPRITE_SLOT, sprite())
