"""🗂 Завести справу руками: «ця тека — ДАХмО 315-1-8433, метрична книга, 1858».

Досі опис справи міг з'явитись лише двома шляхами: з каталогу архіву або з
сайдкара, який писали скрипти дослідницького конвеєра. Для людини зі сканами на
диску це означало, що її тека лишається безіменною назавжди — бібліотека бачить
кадри, але не знає ні шифри, ні назви, ні років. А без шифри справа не має
ключа, тобто не має ні обліку прочитаного, ні місця в реєстрі, ні можливості
процитувати знахідку.

🔴 Опис пишеться В теку справи (`_source.json`), а не в окрему базу. Причина
конкретна: тека переїжджає між дисками, копіюється на резервний носій і
приїжджає до колеги — і опис мусить їхати з нею. Зовнішня база лишила б після
такого переїзду теку без імені, а базу з посиланням у нікуди.

🔴 Своє не затирається. Сайдкар, написаний завантажувачем архіву, несе
провенанс (звідки качали, коли, яким запитом); правка людини має його доповнити,
а не стерти — інакше перший же ручний коментар знищив би доказ походження.
"""
from __future__ import annotations

import json
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from nyshporka import library as L
from nyshporka.utils import text as T

SIDECAR = "_source.json"

#: «315-1-8433», «ДАХмО 315-1-8433», «ф.315 оп.1 спр.8433», «Ф. 211 Оп. 3 Д. 140»,
#: «ДАВіО Р-6129-24-5» (радянський фонд), «ЦДІАЛ 201-4б-15» (літера в описі).
#:
#: 🔴 Номер фонду й опису описують ЦЕГЛИНИ З `library`, а не власні шаблони. Цей
#: розбір і той, що шукає шифру в тексті, різні за призначенням — тут людський
#: запис із «ф./оп./спр.», там пошук у прозі, — і зводити їх в один не можна. А
#: от відповідь на питання «що таке номер фонду» мусить бути одна: доти кожен
#: ніс власну, і вони розійшлись — бібліотека навчилась читати «Р-6129», а
#: `nysh case` на тій самій шифрі казав «не розібрав».
#:
#: ⚠ Літерний префікс фонду захоплюється лише разом із ДЕФІСОМ, інакше хвіст
#: назви архіву («ДАВіО ») поїхав би в номер фонду.
_SHIFRA_RE = re.compile(
    # ⚠ Негативний перегляд уперед відрізає ПОЗНАЧКИ ПОЛІВ. Дозволивши крапку
    # після назви архіву («ДАКО. 705-1-1»), ми заразом дозволили групі covered
    # проковтнути «ф.» — і «ф. 315-1-8433», форма, яку цей самий докстрінг
    # називає прийнятною, відповідала «архів «ф» невідомий», тобто радила
    # завести архів на ім'я «ф».
    r"(?:(?!(?:ф|оп|спр|д|inv|d)\.?\s)(?P<repo>[A-Za-zА-Яа-яІЇЄҐіїєґ']+)\.?\s+)?"
    rf"(?:ф\.?\s*)?(?P<fond>{L.FOND_TOKEN})\s*[-–/\s]\s*"
    rf"(?:оп\.?\s*|inv\.?\s*)?(?P<opys>{L.OPYS_TOKEN})\s*[-–/\s]\s*"
    r"(?:спр\.?\s*|д\.?\s*|d\.?\s*)?(?P<spr>[\w@]+)",
    re.IGNORECASE)

#: Людські назви архівів → код репозиторію.
#:
#: 🔴 Свідомо НЕ літерал. Доти це була третя копія того самого переліку — і
#: розходилась вона з рештою не гіпотетично: `nysh case` не знав ДАЧО й ДАЧвО,
#: які `library` уже знала, тож той самий архів резолвився по-різному залежно
#: від того, якою командою заводили справу. Перелік один і живе в паку, звідки
#: його розширює й накладка користувача.
#: 🔴 Код зводиться до канонічного (`DAVO` → `DAVIO`), і це не косметика:
#: звідси він їде в `_source.json`, а звідти — у ключ справи. Один архів під
#: двома кодами роздвоює облік, і роздвоює тихо: половина вінницьких справ
#: лягла б під другий код, а «на диску» рахувалось би окремо для кожного.
def _repo_words() -> dict[str, str]:
    from nyshporka.archives.pack import active

    pk = active()
    return {w: pk.canon_repo(c) for w, c in pk.word_index().items()}


def _repo_of_word(word: str) -> str:
    """Слово перед номерами → канонічний код архіву, або порожньо.

    Питає пак, а не власну копію словника: там живе і зведення мішаного письма
    («ДАКО» з латинською «K»), і знання про псевдоніми. Копія тут була б
    четвертою й розійшлась би першою.
    """
    from nyshporka.archives.pack import active

    pk = active()
    code = pk.resolve_code(word)
    return pk.canon_repo(code) if code else ""


class RegisterError(RuntimeError):
    """Справу не завести — з поясненням, чого бракує."""


@dataclass(frozen=True)
class Shifra:
    repo: str
    fond: str
    opys: str
    spr: str

    def as_text(self) -> str:
        """Шифра, як її пише ЛЮДИНА: скороченням архіву, а не нашим кодом.

        🔴 Цей рядок їде в `_source.json`, тобто в теку, яка переїжджає між
        дисками й потрапляє до колег. `DAHMO 315-1-8433` там означало б, що
        паспорт справи навчає писати шифру кодом, якого не існує в жодному
        архівному описі, — і далі цією ж формою людина підпише виписку. Той
        самий різновид витоку, що й `DAVO` замість «ДАВіО» в переліках.
        ⚠ Розбір від цього не страждає: `parse_shifra` приймає і код, і
        скорочення, і псевдоніми.
        """
        from nyshporka.archives.pack import active

        return f"{active().repo_label(self.repo)} {self.fond}-{self.opys}-{self.spr}"

    # ⚠ Тут була властивість `key`, і вона складала ключ сама: `repo/fond/spr`,
    # без опису й завжди. Для фондів, де опис входить у ключ, це схлопувало
    # «211-1-140» (с. Парково) і «211-3-140» (Кишинівський собор) в одну
    # адресу — тобто аркуші однієї книги мовчки дописувались би в іншу.
    # Викликачів вона не мала жодного, тож була зарядженою міною, а не вадою:
    # ключ у пакеті складає лише `library._mk_key`, який знає про описи.
    # Форматні ворота (`tests/test_case_key_builder.py`) її не бачили — `self.`
    # у f-рядку не підпадав під їхню регулярку.


def _no_repo_why(raw: str, word: str) -> str:
    """Чому архів не впізнано — з НАЗВАНОЮ причиною, а не описом стану.

    🔴 Доти повідомлення радило дві речі, і обидві були нездійсненні: «додайте
    назву» там, де назва вже стояла, і «вкажіть окремо» — про параметр, якого
    не було ні у формі, ні в схемі операції, ні в CLI. А головне, воно не
    називало справжню причину: мішане письмо на екрані не видно, тож людина
    читала відмову впізнати рівно те слово, яке щойно ввела правильно.
    """
    from nyshporka.utils import text as T

    if not word:
        return (f"з «{raw}» не видно архіву: перед номерами немає його назви. "
                f"Приклад: «ДАХмО 315-1-8433». Архів можна й вибрати окремим "
                f"полем — тоді шифра лишається як є.")
    why = (f"архів «{word}» невідомий. Виберіть його зі списку — або додайте, "
           f"якщо вашого архіву там немає: назву цього застосунок сам не "
           f"вигадує, інакше та сама шифра в двох архівах злиється в одну "
           f"справу.")
    # ⚠ Мішане письмо саме собою вже не причина відмови: зведення до кирилиці
    # пробується ДО цього тексту (`pack.resolve_code`). Якщо ми тут, слово
    # невідоме й у зведеному вигляді — але назвати підміну все одно варто, бо
    # вона могла зіпсувати саме ту літеру, якою слово відрізняється.
    if T.is_mixed_script(word):
        lat = ", ".join(T.latin_letters_in(word))
        why += (f" До того ж літери {lat} тут латинські, а решта кирилиця — на "
                f"екрані це не видно; наберіть назву одним письмом.")
    return why


def parse_shifra(text: str, *, repo_hint: str = "") -> Shifra:
    """Людський запис шифри → розібрана шифра, або зрозуміла відмова.

    Приймає всі форми, якими люди справді пишуть: «315-1-8433»,
    «ДАХмО 315-1-8433», «ф.315 оп.1 спр.8433», «Ф. 211 Оп. 3 Д. 140».
    """
    # 🔴 Невидиме знімається ДО регулярки, а не діагностується після неї.
    # Символ нульової ширини не входить у клас літер, тож група `repo` просто
    # не збиралась, і відмова казала «перед номерами немає назви архіву» під
    # написом, де назва стоїть. Копіювання з вебсторінки приносить такі символи
    # регулярно, а на вигляд рядка вони не впливають узагалі.
    raw = T.strip_invisible(text or "").strip()
    if not raw:
        raise RegisterError(
            "шифра порожня. Це не формальність: без неї справа не має ключа, "
            "тобто ні обліку прочитаного, ні місця в реєстрі, ні можливості "
            "послатись на знахідку. Приклад: «ДАХмО 315-1-8433».")
    m = _SHIFRA_RE.search(raw)
    if not m:
        raise RegisterError(
            f"не розібрав шифру «{raw}». Приймаю: «ДАХмО 315-1-8433», "
            f"«315-1-8433», «ф.315 оп.1 спр.8433», «Ф. 211 Оп. 3 Д. 140».")
    word = (m.group("repo") or "").strip()
    repo = _repo_of_word(word) or _repo_of_word(repo_hint)
    if not repo:
        raise RegisterError(_no_repo_why(raw, word))
    # 🔴 Фонд зводиться до канону ТІЄЮ САМОЮ функцією, що й у бібліотеці:
    # «Р-6129» кирилицею і «R-6129» латинкою — один фонд. Інакше та сама справа
    # заходила б у облік двома ключами залежно від того, яким письмом її набрали.
    return Shifra(repo=repo, fond=str(L._norm_fond(m.group("fond"))),
                  opys=m.group("opys"), spr=str(m.group("spr")).lstrip("0") or "0")


def read_sidecar(case_dir: Path) -> dict[str, Any]:
    """Наявний опис теки — або порожньо. Помилка читання = порожньо, не виняток."""
    for name in (SIDECAR, "meta.json"):
        f = Path(case_dir) / name
        if not f.is_file():
            continue
        try:
            data = json.loads(f.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        if isinstance(data, dict):
            return data
    return {}


def case_path(case_dir: str | Path) -> Path:
    """Тека справи як абсолютний шлях.

    🔴 Реєстр справ зберігає шляхи відносними до простору — щоб простір можна
    було перенести на інший диск чи віддати колезі. Через це `Path(...)` від
    такого рядка резолвиться від поточної теки процесу, а вона в демона й у
    командному рядку різна: та сама справа, натиснута кнопкою, «зникала» б, а
    з-під `cd` у корені простору знаходилась. Тому відносний шлях завжди
    добудовується коренем простору, і лише абсолютний береться як є.
    """
    p = Path(case_dir).expanduser()
    if not p.is_absolute():
        from nyshporka.core.workspace import workspace

        p = workspace().root / p
    return p.resolve()


def reachable(case_dir: Path) -> bool:
    """Чи побачить цю теку збірка бібліотеки.

    🔴 Сканується лише `<простір>/data/raw` (та оголошені корені справ). Тека
    на робочому столі чи на флешці лишається невидимою — а саме туди й показує
    людина, яка щойно поставила застосунок.

    Питання не косметичне: без нього заведення справи проходило з ✅, опис
    писався в теку — і на цьому все закінчувалось. Реєстр лишався порожній,
    облік прочитаного не мав куди лягти, пошук нічого не знаходив, вивантаження
    відмовляло. Кожен наступний крок падав з окремої причини, і жодна з них не
    називала справжню.
    """
    from nyshporka.core.workspace import workspace

    for root in workspace().case_roots():
        try:
            case_dir.relative_to(root.resolve())
        except ValueError:
            continue
        return True
    return False


#: Чим людина каже «зітри це поле».
#:
#: 🔴 Порожнє поле лишає попереднє значення — і це правильно: правка одного
#: заголовка не має стирати роки, які хтось уже уточнив. Але зворотної дії не
#: було ЖОДНОЇ: помилково введена назва чи рік лишались назавжди, а підказка у
#: формі чесно радила «стерти опис можна лише правкою файлу `_source.json` у
#: теці» — тобто єдиний вихід із застосунку вів у текстовий редактор.
#: ⚠ Тире, а не порожній рядок: порожнє поле означає «не чіпай» і мусить далі
#: означати саме це, інакше кожне збереження форми стирало б усе, чого людина
#: не переписала.
ERASE = ("-", "—", "–")


def _erase(val: object) -> bool:
    """Чи це прохання стерти поле, а не нове значення."""
    return isinstance(val, str) and val.strip() in ERASE


def _no_dir_reason(case_dir: str | Path, resolved: Path) -> str:
    """Чому теки немає — і чи людина взагалі теку називала.

    🔴 «теки немає: <поточна тека>/ДАХмО 315-1-8433» — відповідь про стан
    диска, якого не існує: команда мовчки склеїла ШИФРУ з поточною текою і
    видала результат за факт. Ціна заміряна на живому читачі — побачивши той
    рядок, він спитав, чому тека архіву лежить не на місці; насправді матеріал
    лежав рівно там, де мав, а шлях вигадала команда.

    🔴 Резолвити адресу в теку автоматично не можна: `describe` ПИШЕ
    `_source.json`, і помилка на один номер видала б паспорт чужій теці —
    найдорожчий рід помилки в обліку. Тому шлях приходить очима, а команда
    лише називає той, що знає.
    """
    from nyshporka.library import find_by_address, parse_address

    addr = parse_address(str(case_dir))
    if addr is None:
        return f"теки немає: {resolved}"
    where = ""
    try:
        found = find_by_address(addr)
    except Exception:      # бібліотека не зібрана — підказка не критична
        found = []
    if len(found) == 1 and found[0].get("path"):
        where = (f" На диску вона лежить у «{found[0]['path']}» — описуйте цю теку: "
                 f"nysh case \"{found[0]['path']}\" --shifra \"{addr.as_text()}\".")
    return (f"«{case_dir}» — це адреса справи, а не тека зі сканами. "
            f"`nysh case` описує ТЕКУ: перший аргумент — шлях до неї, а шифра "
            f"йде в --shifra.{where} Що вже відомо про справу за цією адресою — "
            f"nysh pages status \"{case_dir}\".")


def describe(case_dir: str | Path, *, shifra: str = "", title: str = "",
             doc_type: str = "", year_from: int | str | None = None,
             year_to: int | str | None = None, place: str = "", note: str = "",
             repo_hint: str = "", film: str = "") -> dict[str, Any]:
    """Записати або доповнити опис справи в її теці. Повертає готовий сайдкар.

    Порожнє поле не затирає наявне: правка одного заголовка не має стирати
    роки, які хтось уже уточнив. А щоб СТЕРТИ поле — тире («-»): доти зворотної
    дії не було зовсім, і помилково введена назва лишалась назавжди.

    🔴 `film` робить виразимим стан «матеріал є, шифра ще ні». Він трапляється
    щоразу, коли справу знайдено за селом у дзеркалі плівок: номер плівки
    відомий, а фонд і опис — ще ні. Доти вибір був недобрий: вигадати шифру (і
    потім розгрібати неправду в обліку) або відкласти роботу. Тепер тека
    описується тим, що про неї справді відомо.

    ⚠ Ключа справи цей стан НЕ отримує, і це навмисно. Провізорний ключ виглядав
    би як архівна шифра, розтікся б по обліку сторінок, реєстру й меті прогонів
    — а в мить, коли шифра встановиться, усе це довелось би переносити. Тут же
    достатньо вписати шифру в цей самий паспорт: наступний `cases build`
    перекладе теку на нормальний ключ сам, і переносити нема чого.
    """
    d = case_path(case_dir)
    if not d.is_dir():
        raise RegisterError(_no_dir_reason(case_dir, d))

    old = read_sidecar(d)
    sh: Shifra | None = None
    if shifra:
        sh = parse_shifra(shifra, repo_hint=repo_hint)
    elif old.get("shifra"):
        sh = parse_shifra(str(old["shifra"]), repo_hint=repo_hint)
    film = " ".join((film or "").split())
    if sh is None and not (film or old.get("film")):
        raise RegisterError(
            "у теці ще немає опису, тож потрібна шифра: саме вона робить теку "
            "справою, а не купою файлів. Якщо шифру ще не встановлено, назвіть "
            "плівку — `--film <номер>`: тоді тека опишеться тим, що про неї "
            "відомо, і не вигадуватиме шифри.")

    out: dict[str, Any] = dict(old)
    if film:
        out["film"] = film
    if sh is None:
        # Стан заявлений, а не пропущений: без цього поля наступна сесія читає
        # теку без шифри як «забули описати» й описує її навмання.
        out["unidentified"] = True
        out.pop("shifra", None)
    else:
        out.pop("unidentified", None)
        out["shifra"] = sh.as_text()
        out["repo"] = sh.repo
        out["fond"] = sh.fond
        out["opys"] = sh.opys
        out["spr"] = sh.spr
    for key, val in (("title", title), ("doc_type", doc_type), ("place", place),
                     ("note", note)):
        if _erase(val):
            out.pop(key, None)
        elif val:
            out[key] = val
    for key, year in (("year_from", year_from), ("year_to", year_to)):
        if _erase(year):
            out.pop(key, None)
        elif year is not None and str(year).strip():
            try:
                out[key] = int(str(year).strip())
            except ValueError:
                raise RegisterError(
                    f"«{year}» не рік. Чекаю число (1858) або тире, щоб "
                    f"стерти.") from None
    # 🔴 Слід ручної правки лишається назавжди. Опис, узятий із каталогу архіву,
    # і опис, набраний людиною, мають різну вагу — і не розрізнити їх пізніше
    # означає не знати, чому назва саме така.
    out["desc_source"] = "hand" if not old else out.get("desc_source", "hand")
    out["edited_by_hand"] = True

    tmp = d / (SIDECAR + ".tmp")
    tmp.write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding="utf-8")
    tmp.replace(d / SIDECAR)
    return out


def forget(case_dir: str | Path) -> bool:
    """Прибрати ручний опис. Повертає True, якщо було що прибирати.

    ⚠ Прибирає рівно сайдкар, нічого більше: скани й прочитане лишаються. Без
    опису тека просто повертається в стан «матеріал без шифри».
    """
    f = case_path(case_dir) / SIDECAR
    if not f.is_file():
        return False
    f.unlink()
    return True
