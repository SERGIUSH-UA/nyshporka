"""Контраст кольорів — чиста арифметика WCAG.

Потрібна не для краси. Палітру задають на світлій темі й на великому екрані, а
читають її на ноутбуці в читальній залі: половина застосунку — сірий текст
підказок і кольорові бейджі рушіїв, і рівно вони випадають першими. Ця пара
функцій дає тестові число замість ока.
"""
from __future__ import annotations

#: Поріг WCAG 2.1 AA для звичайного тексту. Великий текст (≥18.66px жирний або
#: ≥24px) допускає 3.0, але в застосунку такого немає — бейджі рушіїв набрані
#: дрібним, тож пом'якшувати поріг нема на що.
AA_TEXT = 4.5
#: Поріг для нетекстового: рамки, розділювачі, стан фокуса (WCAG 1.4.11).
AA_NONTEXT = 3.0


def rgb(value: str) -> tuple[int, int, int]:
    """`#rrggbb` (або `#rgb`) → канали 0-255."""
    h = value.strip().lstrip("#")
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    if len(h) != 6:
        raise ValueError(f"не колір: {value!r}")
    return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)


def luminance(value: str) -> float:
    """Відносна яскравість за WCAG 2.1."""
    def channel(c: int) -> float:
        s = c / 255
        return s / 12.92 if s <= 0.04045 else ((s + 0.055) / 1.055) ** 2.4

    r, g, b = (channel(c) for c in rgb(value))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast(a: str, b: str) -> float:
    """Відношення контрасту двох кольорів: від 1.0 (однакові) до 21.0."""
    la, lb = luminance(a), luminance(b)
    lo, hi = min(la, lb), max(la, lb)
    return (hi + 0.05) / (lo + 0.05)


def hue(value: str) -> float:
    """Тон кольору в градусах (0-360). Сірий дає 0.0."""
    r, g, b = (c / 255 for c in rgb(value))
    hi, lo = max(r, g, b), min(r, g, b)
    d = hi - lo
    if d == 0:
        return 0.0
    if hi == r:
        h = ((g - b) / d) % 6
    elif hi == g:
        h = (b - r) / d + 2
    else:
        h = (r - g) / d + 4
    return h * 60


def hue_gap(a: str, b: str) -> float:
    """Найкоротша відстань між тонами, 0-180.

    🔴 Саме ця величина розрізняє бейджі рушіїв, а не контраст: кольори трьох
    рушіїв навмисно мають близьку яскравість, щоб однаково читатись на полотні.
    Тобто контраст між ними низький за побудовою, і міряти розрізненність ним
    означало б міряти не те.
    """
    d = abs(hue(a) - hue(b)) % 360
    return min(d, 360 - d)
