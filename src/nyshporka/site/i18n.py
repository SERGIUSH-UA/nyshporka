def t(lang: str, key: str, **kw: Any) -> str:
    """Рядок оболонки мовою `lang`; бракує — українською, а нема й там — ключ."""
    text = S.get(lang, {}).get(key) or S[DEFAULT].get(key) or key
    return text.format(**kw) if kw else text


def languages(wanted: list[str] | None, default: str) -> list[str]:
    """Мови збірки: основна першою, далі решта з переліку, без повторів і невідомих."""
    main = default if default in LANGS else DEFAULT
    rest = [x for x in (wanted if wanted is not None else list(LANGS)) if x in LANGS and x != main]
    return [main, *dict.fromkeys(rest)]


